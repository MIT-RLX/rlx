  (* `|z|²` of a complex tensor, as a real tensor. *)
  let complex_norm_sq self (z : int) =
    let r = c_rlx_graph_complex_norm_sq (Some self) z in
    r

  let add self (a : int) (b : int) =
    let r = c_rlx_graph_add (Some self) a b in
    r

  let sub self (a : int) (b : int) =
    let r = c_rlx_graph_sub (Some self) a b in
    r

  let mul self (a : int) (b : int) =
    let r = c_rlx_graph_mul (Some self) a b in
    r

