(* This process's place in a mesh of rlx nodes: point-to-point messages, *)
(* collectives, and the ship-graph protocol (a coordinator ships a stage or a *)
(* training job; generic workers run it on their own hardware). *)
module Group = struct
  type t = group_h

  (* Free the handle now (it is unusable afterwards). *)
  let close self = c_rlx_group_free self

  (* Join a mesh as `rank` of `world`. options: {peers: ["host:port", …], *)
  (* topology: "mesh" | "star", device: "auto", discover: {port, data_port, *)
  (* via}, heap_mb}. Blocks until every peer connects. *)
  let connect ?options (rank : int) (world : int) =
    let r = c_rlx_group_connect rank world (Option.map Json.to_string options) in
    r

  (* Join with RANK / WORLD / PEERS / TOPOLOGY / DEVICE / DISCOVER from the environment. *)
  let from_env () =
    let r = c_rlx_group_from_env () in
    r

  (* This node's rank. *)
  let rank self =
    let r = c_rlx_group_rank (Some self) in
    r

  (* Ranks in the mesh. *)
  let world self =
    let r = c_rlx_group_world (Some self) in
    r

  (* Whether this is rank 0. *)
  let is_leader self =
    let r = c_rlx_group_is_leader (Some self) in
    r

  (* Wait until every rank arrives. *)
  let barrier self =
    c_rlx_group_barrier (Some self)

  (* Send f32 values to rank `to` under `tag`. *)
  let send self (to_ : int) (tag : int) (data : float array) =
    c_rlx_group_send (Some self) to_ tag data (Array.length data)

  (* Receive f32 values from rank `from` under `tag`. *)
  let recv self (from : int) (tag : int) =
    let r = c_rlx_group_recv (Some self) from tag in
    r

  (* Reduce across every rank: op "sum" | "mean" | "max" | "min". *)
  let all_reduce ?(op = "sum") self (data : float array) =
    let r = c_rlx_group_all_reduce (Some self) data (Array.length data) (Some op) in
    r

  (* Every rank's values, concatenated in rank order. *)
  let all_gather self (data : float array) =
    let r = c_rlx_group_all_gather (Some self) data (Array.length data) in
    r

  (* Rank `root`'s values, on every rank; other ranks pass a buffer of the root's length. *)
  let broadcast self (root : int) (data : float array) =
    let r = c_rlx_group_broadcast (Some self) root data (Array.length data) in
    r

  (* Coordinator: the capabilities each worker announced, [{rank, devices, platform, role}]. *)
  let collect_caps self =
    let r = c_rlx_group_collect_caps (Some self) in
    (Json.of_string (Option.value r ~default:"null"))

  (* Coordinator: ship a stage of `graph` to worker `rank`. options: {input, *)
  (* output, device, weights: {param: uri}, packed: {param: uri}, stage_id}. *)
  let ship_stage self (rank : int) (graph : graph_h) (options : Json.t) =
    c_rlx_group_ship_stage (Some self) rank (Some graph) (Some (Json.to_string options))

  (* Send an activation to rank `to`. *)
  let send_activation self (to_ : int) (data : float array) =
    c_rlx_group_send_activation (Some self) to_ data (Array.length data)

  (* Receive an activation from rank `from`. *)
  let recv_activation self (from : int) =
    let r = c_rlx_group_recv_activation (Some self) from in
    r

  (* Worker: announce, receive a stage, serve activations until the *)
  (* coordinator finishes (or `steps`). options: {steps}. Returns {rank, device, platform, activations}. *)
  let serve_worker ?options self =
    let r = c_rlx_group_serve_worker (Some self) (Option.map Json.to_string options) in
    (Json.of_string (Option.value r ~default:"null"))

  (* Coordinator: ship a data-parallel training job for backward `graph` to *)
  (* worker `rank`. spec: {params: [{name, uri}], data: [{input, uri, elem, *)
  (* shard_start, shard_len}], grad_start, loss_index, seed_input, momentum, *)
  (* lr_per_epoch, batch, device, push_data}. *)
  let ship_train self (rank : int) (graph : graph_h) (spec : Json.t) =
    c_rlx_group_ship_train (Some self) rank (Some graph) (Some (Json.to_string spec))

  (* Train this rank's shard of a job in lockstep with the workers; returns *)
  (* {metrics, params}. *)
  let run_train self (graph : graph_h) (spec : Json.t) =
    let r = c_rlx_group_run_train (Some self) (Some graph) (Some (Json.to_string spec)) in
    (Json.of_string (Option.value r ~default:"null"))

  (* Worker: announce, receive a training job, train in lockstep; returns {rank, platform, metrics, params}. *)
  let serve_trainer ?options self =
    let r = c_rlx_group_serve_trainer (Some self) (Option.map Json.to_string options) in
    (Json.of_string (Option.value r ~default:"null"))
end

