  (* One part per independent subgraph; the parts import nothing. *)
  let components (graph : graph_h) =
    let r = c_rlx_partition_components (Some graph) in
    r

  (* The number of parts. *)
  let num_parts self =
    let r = c_rlx_partition_num_parts (Some self) in
    r

  (* A copy of one part's graph. *)
  let graph self (part : int) =
    let r = c_rlx_partition_graph (Some self) part in
