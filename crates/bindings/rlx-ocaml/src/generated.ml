(* Trains a graph's parameters: forward, backward, optimizer, on one device. *)
module Trainer = struct
  type t = trainer_h

  (* Free the handle now (it is unusable afterwards). *)
  let close self = c_rlx_trainer_free self

  (* Takes `graph` (consumed): its first output is the loss. `wrt` are the *)
  (* trainable params; `initial` their starting values. options: {optimizer, *)
  (* device, resident, clip_norm, …}. *)
  let create ?options (graph : graph_h) (wrt : string array) (initial : (string * float array) list) =
    let in_initial = Support.inputs initial in
    c_rlx_trainer_new (Some graph) wrt (Array.length wrt) in_initial.inames in_initial.idata in_initial.ilens (Array.length in_initial.inames) (Option.map Json.to_string options)

  (* One optimizer step on a batch; returns the loss. *)
  let step self (batch : (string * float array) list) =
    let in_batch = Support.inputs batch in
    let r = c_rlx_trainer_step (Some self) in_batch.inames in_batch.idata in_batch.ilens (Array.length in_batch.inames) in
    r

  (* The loss on a batch, no update. *)
  let evaluate self (batch : (string * float array) list) =
    let in_batch = Support.inputs batch in
    let r = c_rlx_trainer_evaluate (Some self) in_batch.inames in_batch.idata in_batch.ilens (Array.length in_batch.inames) in
    r

  (* Stop updating `names` (all when omitted); returns how many are frozen. *)
  let freeze ?names self =
    let r = c_rlx_trainer_freeze (Some self) (Option.value names ~default:[||]) (Array.length (Option.value names ~default:[||])) in
    r

  (* Resume updating `names` (all when omitted); returns how many are frozen. *)
  let unfreeze ?names self =
    let r = c_rlx_trainer_unfreeze (Some self) (Option.value names ~default:[||]) (Array.length (Option.value names ~default:[||])) in
    r

  (* Frozen parameter names. *)
  let frozen self =
    let r = c_rlx_trainer_frozen (Some self) in
    (Json.strings (Option.value r ~default:"[]"))

  (* Trainable parameter names. *)
  let trainable self =
    let r = c_rlx_trainer_trainable (Some self) in
    (Json.strings (Option.value r ~default:"[]"))

  (* The last step's gradient norm, once one is known. *)
  let grad_norm self =
    let r = c_rlx_trainer_grad_norm (Some self) in
    (match r with (x, true) -> Some x | _ -> None)

  (* Whether parameters live on the device between steps. *)
  let is_resident self =
    c_rlx_trainer_is_resident (Some self)

  (* The current parameters. *)
  let params self =
    let r = c_rlx_trainer_params (Some self) in
    (Array.to_list r)

  (* Replace parameters by name; returns how many matched. *)
  let set_params self (params : (string * float array) list) =
    let in_params = Support.inputs params in
    let r = c_rlx_trainer_set_params (Some self) in_params.inames in_params.idata in_params.ilens (Array.length in_params.inames) in
    r

  (* Change the learning rate. *)
  let set_lr self (lr : float) =
    c_rlx_trainer_set_lr (Some self) lr

  (* Steps taken. *)
  let steps self =
    let r = c_rlx_trainer_steps (Some self) in
    r

  (* The device it trains on. *)
  let device self =
    let r = c_rlx_trainer_device (Some self) in
    (Option.value r ~default:"")

  (* Checkpoint parameters + optimizer state as GGUF; returns tensors written. *)
  let save self (path : string) =
    let r = c_rlx_trainer_save (Some self) (Some path) in
    r

  (* Restore a checkpoint; returns {params, step, lr, …}. *)
  let load self (path : string) =
    let r = c_rlx_trainer_load (Some self) (Some path) in
    (Json.of_string (Option.value r ~default:"null"))

  (* Train a function of the .rlxp package at `path`, whatever the model. *)
  (* options: {function, dims, loss, train ("all" | {params} | {lora: *)
  (* {targets, rank, alpha}} | {sae: {tap, width, l1}}), optimizer, device, *)
  (* policy, clip_norm, resident}, over the package's own `train`. *)
  let from_package ?options (path : string) =
    let r = c_rlx_trainer_from_package (Some path) (Option.map Json.to_string options) in
    r

  (* Write what a package trainer trained: LoRA factors as an adapter *)
  (* package, an SAE as its own package, else the trained package. *)
  let save_package ?name self (path : string) =
    c_rlx_trainer_save_package (Some self) (Some path) name
end

