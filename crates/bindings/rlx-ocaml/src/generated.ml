(* A graph under construction. Its builders (`matmul`, `conv2d`, …) are the op *)
(* table's (`table.rs`); these rows are its lifecycle. *)
module Graph = struct
  type t = graph_h

  (* Free the handle now (it is unusable afterwards). *)
  let close self = c_rlx_graph_free self

  let create ?(name = "graph") () =
    c_rlx_graph_new (Some name)

  (* A deep copy — compile one, keep building on the other. *)
  let clone self =
    let r = c_rlx_graph_clone (Some self) in
    r

  (* Whether a compile (or a body-graph argument) consumed it. *)
  let is_consumed self =
    c_rlx_graph_is_consumed (Some self)

  (* A runtime input. `dtype` defaults to f32. *)
  let input ?(dtype = "f32") self (name : string) (shape : int array) =
    let r = c_rlx_graph_input (Some self) (Some name) shape (Array.length shape) (Some dtype) in
    r

  (* A trainable / loadable weight, filled by `set_params` at run time. *)
  let param ?(dtype = "f32") self (name : string) (shape : int array) =
    let r = c_rlx_graph_param (Some self) (Some name) shape (Array.length shape) (Some dtype) in
    r

  (* A rank-0 literal that broadcasts in binary ops. *)
  let constant ?(dtype = "f32") self (value : float) =
    let r = c_rlx_graph_constant (Some self) value (Some dtype) in
    r

  (* A constant tensor of zeros. *)
  let zeros ?(dtype = "f32") self (dims : int array) =
    let r = c_rlx_graph_zeros (Some self) dims (Array.length dims) (Some dtype) in
    r

  (* A constant tensor filled with `value`. *)
  let full ?(dtype = "f32") self (dims : int array) (value : float) =
    let r = c_rlx_graph_full (Some self) dims (Array.length dims) value (Some dtype) in
    r

  (* Mark the graph's outputs, in order. *)
  let set_outputs self (outputs : int array) =
    c_rlx_graph_set_outputs (Some self) outputs (Array.length outputs)

  (* The output node ids, in order. *)
  let outputs self =
    let r = c_rlx_graph_outputs (Some self) in
    r

  (* Name output `index`, so a compiled graph finds it by name. *)
  let name_output self (index : int) (name : string) =
    c_rlx_graph_name_output (Some self) index (Some name)

  (* Each output's name, in order; "" for an unnamed one. *)
  let output_names self =
    let r = c_rlx_graph_output_names (Some self) in
    (Json.strings (Option.value r ~default:"[]"))

  (* `(dims, dtype)` of a node; a dynamic dim reads back as `-1`. *)
  let shape_of self (id : int) =
    let r = c_rlx_graph_shape_of (Some self) id in
    (Json.ints (Option.value r ~default:"[]"))

  let node_count self =
    let r = c_rlx_graph_node_count (Some self) in
    r

  let name self =
    let r = c_rlx_graph_name (Some self) in
    (Option.value r ~default:"")

  (* Every `Param` name, in creation order — what `set_params` must cover. *)
  let param_names self =
    let r = c_rlx_graph_param_names (Some self) in
    (Json.strings (Option.value r ~default:"[]"))

  (* Distinct op kinds present, sorted. *)
  let op_kinds self =
    let r = c_rlx_graph_op_kinds (Some self) in
    (Json.strings (Option.value r ~default:"[]"))

  (* Shape-inferred matmul. *)
  let matmul self (lhs : int) (rhs : int) =
    let r = c_rlx_graph_matmul (Some self) lhs rhs in
    r

  (* Matmul with an explicit output shape, for a layout inference would not pick. *)
  let matmul_with_shape ?(dtype = "f32") self (lhs : int) (rhs : int) (out_shape : int array) =
    let r = c_rlx_graph_matmul_with_shape (Some self) lhs rhs out_shape (Array.length out_shape) (Some dtype) in
    r

  (* `x = A⁻¹·b`; `x` takes `b`'s shape unless `out_shape` is given. *)
  let dense_solve ?out_shape ?(dtype = "f32") self (a : int) (b : int) =
    let r = c_rlx_graph_dense_solve (Some self) a b (Option.value out_shape ~default:[||]) (Array.length (Option.value out_shape ~default:[||])) (Some dtype) in
    r

  let batched_dense_solve ?out_shape ?(dtype = "f32") self (a : int) (b : int) =
    let r = c_rlx_graph_batched_dense_solve (Some self) a b (Option.value out_shape ~default:[||]) (Array.length (Option.value out_shape ~default:[||])) (Some dtype) in
    r

  let cholesky self (a : int) =
    let r = c_rlx_graph_cholesky (Some self) a in
    r

  let det self (a : int) =
    let r = c_rlx_graph_det (Some self) a in
    r

  let logdet self (a : int) =
    let r = c_rlx_graph_logdet (Some self) a in
    r

  (* Symmetric eigendecomposition → `(eigenvalues, eigenvectors)`. *)
  let eigh self (a : int) =
    let (r0, r1) = c_rlx_graph_eigh (Some self) a in
    (r0, r1)

  (* Batched symmetric eigendecomposition → `(eigenvalues, eigenvectors)`. *)
