//! The C ABI for rlx: `include/rlx.h`.
//!
//! Every language with C interop reaches rlx through this — Swift (see
//! `crates/bindings/rlx-swift`), Go, C#, Java, Ruby, Julia, Zig. The logic is
//! `rlx-bind`'s, shared with rlx-js and pyrlx; this crate only converts C
//! values.
//!
//! # Conventions
//!
//! * Every function returns an `int32_t` status: `RLX_OK` (0) or a negative
//!   `RLX_ERR_*`. On failure `rlx_last_error()` holds the message (per thread,
//!   valid until the next failing call on that thread).
//! * Objects are opaque handles (`RlxGraph*`, `RlxSession*`, …) created by
//!   `rlx_*_new` / returned through an out-pointer, and released with the
//!   matching `rlx_*_free`. Freeing `NULL` is a no-op.
//! * Arrays go in as pointer + length. Results come back through out-pointers;
//!   buffers rlx allocates (`RlxU32s`, `RlxF32s`, `RlxBytes`, `char*`) are freed
//!   with `rlx_u32s_free` / `rlx_f32s_free` / `rlx_bytes_free` /
//!   `rlx_string_free`. Structured results (reports, shapes, name lists) are
//!   JSON strings.
//! * An optional node is `RLX_NONE`; an optional string, array or scalar is a
//!   `NULL` pointer. A defaulted string argument also takes `NULL` for its
//!   default.
//! * A Rust panic inside rlx is caught and returned as `RLX_ERR_PANIC` —
//!   except under `panic = "abort"` (the iOS profile), which aborts by design.
//!
//! The graph-builder functions (`rlx_graph_<op>`) are generated by
//! `rlx-bindgen` from the op table in `rlx-bind` (`src/graph_ops.rs`); the
//! header is generated by parsing this crate, so it cannot disagree with it.

