"""Regenerate src/tanh_table.rs from NumPy's `loops_hyperbolic.dispatch.cpp.src`.

Usage: python3 tools/gen_tanh_table.py <numpy>/numpy/_core/src/umath/loops_hyperbolic.dispatch.cpp.src
Extracts `lut18x16` — the 16 x 18 table (per subinterval: b, c0..c16) the
2-lane (NEON) float64 tanh path reads.
"""
import re, sys, pathlib
src = open(sys.argv[1]).read()
i = src.index("lut18x16[] = {"); j = src.index("};", i)
vals = re.findall(r"0x[0-9a-f]+ull", src[i:j])
assert len(vals) == 16 * 18, len(vals)
rows = [vals[r * 18:(r + 1) * 18] for r in range(16)]
out = ["// @generated by tools/gen_tanh_table.py from NumPy 2.3.5", "// `numpy/_core/src/umath/loops_hyperbolic.dispatch.cpp.src` (`lut18x16`). Do not edit.", "",
       "/// Per subinterval: `[b, c0, c1, …, c16]` as IEEE-754 bit patterns.", "pub(crate) const LUT18X16: [[u64; 18]; 16] = ["]
for r in rows:
    out.append("    [" + ", ".join(v.replace("ull", "") for v in r) + "],")
out += ["];", ""]
dst = pathlib.Path(__file__).resolve().parent.parent / "src" / "tanh_table.rs"
dst.write_text("\n".join(out)); print("wrote", dst)
