#[test]
fn sum_matches_numpy() {
    for &(n, seed, scale, want) in SUM_F64 {
        let got = sum(&lcg(n, seed, scale));
        assert_eq!(got.to_bits(), want, "np.sum n={n} seed={seed}: got {got:e}");
        if n > 0 {
            assert_eq!(
                pairwise_sum(&lcg(n, seed, scale)).to_bits(),
                want,
                "pairwise n={n}"
            );
        }
    }
}

/// numpy 2.4.3: `np.sum([]) == np.sum([-0.0]) == np.sum([-0.0]*9) == +0.0`.
#[test]
fn sum_signs_of_zero_match_numpy() {
    for v in [vec![], vec![-0.0], vec![-0.0; 9], vec![-0.0, -0.0]] {
        assert_eq!(sum(&v).to_bits(), 0, "np.sum({v:?})");
    }
    // numpy's internal pairwise loop itself starts from -0.0.
    assert_eq!(pairwise_sum(&[]).to_bits(), (-0.0f64).to_bits());
}

#[test]
fn pairwise_sum_f32_matches_numpy() {
    for &(n, seed, scale, want) in SUM_F32 {
        let x: Vec<f32> = lcg(n, seed, scale as f64)
            .iter()
            .map(|&v| v as f32)
            .collect();
        let got = pairwise_sum_f32(&x);
        assert_eq!(
            got.to_bits(),
            want,
            "np.sum(f32) n={n} seed={seed}: got {got:e}"
        );
    }
}

#[test]
fn round_half_even_matches_numpy() {
    for &(x, want) in ROUND {
        let x = f64::from_bits(x);
        assert_eq!(round_half_even(x).to_bits(), want, "np.round({x:e})");
    }
}

#[test]
fn linspace_matches_numpy() {
    for &(a, b, n, want) in LINSPACE {
        let got: Vec<u64> = linspace(a, b, n).iter().map(|v| v.to_bits()).collect();
        assert_eq!(got, want, "np.linspace({a}, {b}, {n})");
    }
}

#[test]
fn sin_cos_separate_is_two_libm_calls() {
    let mut s = 1u64;
    for _ in 0..100_000 {
        s ^= s << 13;
        s ^= s >> 7;
        s ^= s << 17;
        let x = ((s >> 11) as f64 / (1u64 << 53) as f64 - 0.5) * 200.0;
        let (sn, cs) = sin_cos_separate(x);
        assert_eq!(sn.to_bits(), std::hint::black_box(x).sin().to_bits());
        assert_eq!(cs.to_bits(), std::hint::black_box(x).cos().to_bits());
    }
}
