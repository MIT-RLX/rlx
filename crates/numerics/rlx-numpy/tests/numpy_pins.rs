//! Values recorded from numpy 2.4.3 (see the generator in the header of each table).
//! Inputs come from a 64-bit LCG mapped to `((s >> 11) · 2⁻⁵³ − 0.5) · scale`, so
//! they are exact in both languages.

use rlx_numpy::*;

fn lcg(n: usize, seed: u64, scale: f64) -> Vec<f64> {
    let mut s = seed;
    (0..n)
        .map(|_| {
            s = s
                .wrapping_mul(6364136223846793005)
                .wrapping_add(1442695040888963407);
            ((s >> 11) as f64 * 2f64.powi(-53) - 0.5) * scale
        })
        .collect()
}

