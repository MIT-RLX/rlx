"""Regenerate src/factorial_table.rs from Boost.Math's `double` factorial table.

Usage: python3 tools/gen_factorials.py [path/to/boost/math/special_functions/detail/unchecked_factorial.hpp]

The literals are parsed and rounded to double by Python's float(), the same
correctly-rounded decimal conversion the C++ compiler performs. (All 171 equal
float(math.factorial(n)); the script asserts it, so a Boost change is noticed.)
"""
import math, re, struct, sys, pathlib

hpp = sys.argv[1] if len(sys.argv) > 1 else "/opt/homebrew/include/boost/math/special_functions/detail/unchecked_factorial.hpp"
src = open(hpp).read().split("\n")
start = next(i for i, l in enumerate(src)
             if "const boost::math::array<double, 171> unchecked_factorial_data<double, b>::factorials = {{" in l)
vals = []
for l in src[start + 1:]:
    if "}}" in l:
        break
    vals += [float(t) for t in re.findall(r"[0-9.]+e[0-9+-]+|[0-9]+\.[0-9]*", l.split("//")[0])]
assert len(vals) == 171, len(vals)
assert all(v == float(math.factorial(i)) for i, v in enumerate(vals))
bits = lambda v: struct.unpack("<Q", struct.pack("<d", v))[0]
out = ["// @generated by tools/gen_factorials.py from Boost.Math `unchecked_factorial.hpp`",
       "// (the `double` table, 171 entries). Do not edit by hand.", "",
       "/// `n!` for `n = 0..=170`, exactly as Boost stores it for `double`.",
       "pub(crate) const FACTORIALS: [f64; 171] = ["]
out += ["    f64::from_bits(0x%016x), // %d!" % (bits(v), i) for i, v in enumerate(vals)]
out += ["];", ""]
dst = pathlib.Path(__file__).resolve().parent.parent / "src" / "factorial_table.rs"
dst.write_text("\n".join(out))
print("wrote", dst)
