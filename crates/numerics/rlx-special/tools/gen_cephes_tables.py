"""Regenerate src/cephes_tables.rs from scipy/xsf's cephes headers.

Usage: python3 tools/gen_cephes_tables.py <xsf>/include/xsf/cephes
Extracts `igam_asymp_coeff_d[K][N]` (igam_asymp_coeff.h). Each decimal literal is
rounded to double by Python's float() — the correctly rounded conversion the
compiler performs.
"""
import pathlib, re, struct, sys
root = pathlib.Path(sys.argv[1])
src = (root / "igam_asymp_coeff.h").read_text()
K = int(re.search(r"igam_asymp_coeff_K\s*=\s*(\d+)", src).group(1))
N = int(re.search(r"igam_asymp_coeff_N\s*=\s*(\d+)", src).group(1))
body = src[src.index("igam_asymp_coeff_d"):]
body = body[body.index("{") + 1:]
body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
nums = re.findall(r"[-+]?(?:\d+\.\d*|\.\d+|\d+)(?:[eE][-+]?\d+)?", body)
vals = [float(x) for x in nums[: K * N]]
assert len(vals) == K * N, (len(vals), K, N)
bits = lambda v: struct.unpack("<Q", struct.pack("<d", v))[0]
out = ["// @generated by tools/gen_cephes_tables.py from scipy/xsf `cephes/igam_asymp_coeff.h`.",
       "// Do not edit by hand.", "",
       f"pub(crate) const IGAM_ASYMP_K: usize = {K};", f"pub(crate) const IGAM_ASYMP_N: usize = {N};", "",
       "/// `igam_asymp_coeff_d[k][n]` (DLMF 8.12 coefficients), row-major.",
       f"pub(crate) const IGAM_ASYMP_D: [[f64; {N}]; {K}] = ["]
for k in range(K):
    out.append("    [" + ", ".join("f64::from_bits(0x%016x)" % bits(v) for v in vals[k * N:(k + 1) * N]) + "],")
out += ["];", ""]
dst = pathlib.Path(__file__).resolve().parent.parent / "src" / "cephes_tables.rs"
dst.write_text("\n".join(out))
print("wrote", dst, K, "x", N)
