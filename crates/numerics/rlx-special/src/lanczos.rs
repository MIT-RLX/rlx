/// `lanczos13m53::lanczos_sum_near_1(dz)`.
pub fn lanczos_sum_near_1(dz: f64) -> f64 {
    const D: [f64; 12] = [
        2.208_709_979_316_623_790_862_569_924_861_841_433_016,
        -3.327_150_580_651_624_233_553_677_113_928_873_034_916,
        1.483_082_862_367_253_753_040_442_933_770_164_111_678,
        -0.199_375_892_761_472_875_731_423_302_625_781_017_200_8,
        0.004_785_200_610_085_071_473_880_915_854_204_301_886_437,
        -0.151_597_301_987_109_238_894_343_762_382_520_809_512_3e-5,
        -0.275_290_770_290_312_646_600_420_734_503_832_781_871_3e-7,
        0.307_558_017_479_134_849_273_794_734_003_999_282_954_6e-7,
        -0.193_311_789_888_082_834_869_254_139_484_120_428_804_7e-7,
        0.869_092_618_103_805_703_952_612_742_200_249_896_017_2e-8,
        -0.249_950_515_148_786_833_568_027_390_935_407_193_838_7e-8,
        0.339_464_317_189_313_253_517_010_129_224_083_792_772_5e-9,
    ];
    let mut result = 0.0;
    for (k, &d) in D.iter().enumerate() {
        let k = (k + 1) as f64;
        // `(-d*dz)/(k*dz + k*k)`: `k*k` is an unsigned product, `k*dz + …` fuses.
        result += (-d * dz) / k.mul_add(dz, k * k);
    }
    result
}

/// `lanczos13m53::lanczos_sum_near_2(dz)`.
pub fn lanczos_sum_near_2(dz: f64) -> f64 {
    const D: [f64; 12] = [
        6.565_936_202_082_889_535_528_455_955_485_877_361_223,
        -9.890_777_264_492_067_058_928_808_164_012_819_423_1,
        4.408_830_289_125_943_377_923_077_727_900_630_927_902,
        -0.592_694_108_490_506_179_444_573_362_889_102_402_794_9,
        0.014_225_191_271_924_192_343_150_027_462_521_609_658_31,
        -0.450_660_440_970_717_007_713_655_501_001_854_981_919_2e-5,
        -0.818_369_841_072_435_893_082_373_798_211_947_413_006_9e-7,
        0.914_292_206_816_532_413_206_055_059_121_026_799_207_2e-7,
        -0.574_667_064_214_704_158_749_715_964_931_845_434_811_7e-7,
        0.258_359_256_652_443_923_084_437_894_870_426_229_192_7e-7,
        -0.743_039_670_899_871_970_764_273_557_723_844_958_582_2e-8,
        0.100_914_156_698_756_989_222_143_991_823_004_236_811_2e-8,
    ];
    let mut result = 0.0;
    let z = dz + 2.0;
    for (k, &d) in D.iter().enumerate() {
        let k = (k + 1) as f64;
        // `z + k*z + k*k - 1` parses as `((z + k*z) + k*k) - 1`; only `z + k*z` fuses.
        result += (-d * dz) / ((k.mul_add(z, z) + k * k) - 1.0);
    }
    result
}
