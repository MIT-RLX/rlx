"""Generate tests/vectors/numpy_routing.txt: np.dot / np.matmul results for every
routing branch rlx_linalg::numpy reproduces. Run with NumPy 2.x on macOS (Accelerate) for
tests/vectors/, and on the Linux x86-64 reference (msi: OpenBLAS Haswell) for
tests/vectors/linux-x86_64/ — the directory follows the platform.

Record format (one per line, floats as IEEE-754 hex):
  case <fn> <m> <k> <n> <layout_a> <layout_b>
  A <m*k values, logical row-major>
  B <k*n values, logical row-major>      (absent for same-buffer cases)
  R <result, row-major>
layout: C (C-ordered buffer), F (Fortran-ordered buffer), AT (B is A.T of the same buffer)
fn: dot | matmul | dot_mv | dot_vv
"""
import struct, sys, pathlib, numpy as np
h = lambda a: " ".join("%016x" % struct.unpack("<Q", struct.pack("<d", float(v)))[0] for v in np.ravel(a))
rng = np.random.default_rng(99)
lines = [f"# numpy {np.__version__} routing vectors (generated by tools/gen_numpy_routing.py)"]
def lay(x, l):
    return np.ascontiguousarray(x) if l == "C" else np.asfortranarray(x)
def rec(fn, m, k, n, la, lb, A, B, R):
    lines.append(f"case {fn} {m} {k} {n} {la} {lb}")
    lines.append("A " + h(A))
    if B is not None: lines.append("B " + h(B))
    lines.append("R " + h(R))
for _ in range(120):
    m, k, n = (int(rng.integers(2, 40)) for _ in range(3))
    A = rng.normal(size=(m, k)); B = rng.normal(size=(k, n))
    for la in "CF":
        for lb in "CF":
            a, b = lay(A, la), lay(B, lb)
            rec("dot", m, k, n, la, lb, A, B, np.dot(a, b))
            rec("matmul", m, k, n, la, lb, A, B, a @ b)
    for la in "CF":
        a = lay(A, la)
        rec("dot", m, k, m, la, "AT", A, None, np.dot(a, a.T))
        rec("matmul", m, k, m, la, "AT", A, None, a @ a.T)
        x = rng.normal(size=k)
        rec("dot_mv", m, k, 1, la, "C", A, x, np.dot(a, x))
        rec("matmul", m, k, 1, la, "C", A, x.reshape(k, 1), a @ x.reshape(k, 1))
        y = rng.normal(size=m)
        rec("matmul", 1, m, k, "C", la, y.reshape(1, m), A, y.reshape(1, m) @ a)
    v = rng.normal(size=k); w = rng.normal(size=k)
    rec("dot_vv", 1, k, 1, "C", "C", v, w, np.dot(v, w))
vec = pathlib.Path(__file__).resolve().parent.parent / "tests" / "vectors"
out = (vec if sys.platform == "darwin" else vec / "linux-x86_64") / "numpy_routing.txt"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines) + "\n"); print("wrote", out, len(lines))
