#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn eval_matches_reference() {
        let vals = [-2.0f32, -1.0, -0.0, 0.0, 1.0, 2.0, f32::NAN];
        for &op in &CmpOp::ALL {
            for &a in &vals {
                for &b in &vals {
                    let got = eval_compare(op, a, b);
                    let want = {
                        let r = match op {
                            CmpOp::Eq => a == b,
                            CmpOp::Ne => a != b,
                            CmpOp::Lt => a < b,
                            CmpOp::Le => a <= b,
                            CmpOp::Gt => a > b,
                            CmpOp::Ge => a >= b,
                        };
                        if r { 1.0 } else { 0.0 }
                    };
                    assert_eq!(got, want, "{op:?}({a},{b})");
                }
            }
        }
    }

    #[test]
    fn every_language_emits_all_ops() {
        for lang in [Lang::Wgsl, Lang::Cuda, Lang::Msl, Lang::Glsl, Lang::OpenCl] {
            let m = match lang {
                Lang::Wgsl => wgsl_compare_module(),
                Lang::Cuda => cuda_compare_module(),
                Lang::Msl => msl_compare_module(),
                Lang::Glsl => glsl_compare_module(),
                Lang::OpenCl => opencl_compare_module(),
            };
            assert_eq!(m.matches("case ").count(), CmpOp::ALL.len(), "{lang:?}");
            assert!(m.contains("rlx_compare_apply") && m.contains("default"));
        }
        assert!(wgsl_compare_module().contains("select(0.0, 1.0, a == b)"));
        assert!(cuda_compare_module().contains("(a != b) ? 1.0f : 0.0f"));
    }
}
