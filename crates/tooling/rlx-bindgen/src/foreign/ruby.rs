//! Ruby (Fiddle): the functions bound under their C names, the callback
//! types as `Fiddle::Closure::BlockCaller` makers, the structures as
//! `Fiddle::Importer` structs, and a wrapper per function marshaling by
//! kind (`String` in, `String` and `Array<String>` out).

use super::Config;
use super::header::{Header, Ty};

/// A Fiddle type constant
fn fty(h: &Header, t: &Ty) -> &'static str {
    if t.ptr > 0 || h.callbacks.iter().any(|c| c.name == t.base) {
        return "Fiddle::TYPE_VOIDP";
    }
    match t.base.as_str() {
        "int" => "Fiddle::TYPE_INT",
        "short" => "Fiddle::TYPE_SHORT",
        "double" => "Fiddle::TYPE_DOUBLE",
        "bool" => "Fiddle::TYPE_CHAR",
        "void" => "Fiddle::TYPE_VOID",
        _ => "Fiddle::TYPE_VOIDP",
    }
}

/// An importer struct member's C spelling (pointers as `void*`)
fn member(t: &Ty) -> &'static str {
    if t.ptr > 0 {
        return "void*";
    }
    match t.base.as_str() {
        "int" => "int",
        "short" => "short",
        "double" => "double",
        "bool" => "char",
        _ => "void*",
    }
}

fn comment(d: &str, indent: &str) -> String {
    d.lines().map(|l| format!("{indent}# {l}\n")).collect()
}

fn camel(s: &str) -> String {
    s.split('_')
        .map(|w| {
            let mut c = w.chars();
            c.next()
                .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

pub fn emit(h: &Header, cfg: &Config) -> String {
    let mut o = String::new();
    o += &cfg.fill("# libngspice for Ruby (Fiddle), generated by ngspice-bindgen from\n");
    o += &cfg.fill("# sharedspice.h. Do not edit: run `cargo run -p ngspice-bindgen`.\n\n");
    o += "require \"fiddle\"\nrequire \"fiddle/import\"\n\n";
    o += &cfg.fill("# The libngspice C API (sharedspice.h) for Ruby.\n#\n");
    o += &cfg.fill("#   NgSpice.load                 # $NGSPICE_LIBRARY, else the system's\n");
    o += &cfg.fill("#   cb = NgSpice::SendChar.new { |s, id, user| puts s.to_s; 0 }\n");
    o += &cfg.fill("#   NgSpice.init(cb, nil, nil, nil, nil, nil, nil)\n");
    o += &cfg.fill("module NgSpice\n  extend Fiddle::Importer\n\n");
    for s in &h.structs {
        o += &comment(&s.doc, "  ");
        let ms: Vec<String> = s
            .fields
            .iter()
            .map(|f| format!("\"{} {}\"", member(&f.ty), f.name))
            .collect();
        o += &format!("  {} = struct [{}]\n\n", camel(&s.name), ms.join(", "));
    }
    o += "  # the callback types: `Type.new { |args...| result }` (keep it referenced)\n";
    for c in &h.callbacks {
        o += &comment(&c.doc, "  ");
        let ps: Vec<&str> = c.params.iter().map(|p| fty(h, p)).collect();
        o += &format!(
            "  module {}\n    def self.new(&blk)\n      Fiddle::Closure::BlockCaller.new({}, [{}], &blk)\n    end\n  end\n\n",
            c.name,
            fty(h, &c.ret),
            ps.join(", ")
        );
    }
    o += "  @lib = nil\n  @fns = {}\n\n";
    o += &cfg.fill("  # libngspice: `path`, else $NGSPICE_LIBRARY, else the system's\n");
    o += &cfg.fill("  def self.load(path = ENV.fetch(\"NGSPICE_LIBRARY\", \"libngspice.dylib\"))\n    @lib = Fiddle.dlopen(path)\n    @fns = {}\n  end\n\n");
    o += "  def self.fn(name, args, ret)\n    @fns[name] ||= Fiddle::Function.new(@lib[name.to_s], args, ret)\n  end\n\n";
    o += "  # the functions under their C names\n";
    for f in &h.funcs {
        let names: Vec<String> = f.params.iter().map(|p| p.name.clone()).collect();
        let ps: Vec<&str> = f.params.iter().map(|p| fty(h, &p.ty)).collect();
        o += &comment(&f.doc, "  ");
        o += &format!(
            "  def self.{}({})\n    fn(:{}, [{}], {}).call({})\n  end\n\n",
            f.name,
            names.join(", "),
            f.name,
            ps.join(", "),
            fty(h, &f.ret),
            names.join(", ")
        );
    }
    o += "  def self.str(p)\n    p.null? ? nil : p.to_s\n  end\n\n";
    o += "  def self.strs(p)\n    out = []\n    return out if p.null?\n    i = 0\n    while (q = Fiddle::Pointer.new((p + i * Fiddle::SIZEOF_VOIDP)[0, Fiddle::SIZEOF_VOIDP].unpack1(\"J\"))) && !q.null?\n      out << q.to_s\n      i += 1\n    end\n    out\n  end\n\n";
    o += "  def self.strarray(xs)\n    strs = xs.map { |x| Fiddle::Pointer[x.to_s + \"\\0\"] }\n    a = Fiddle::Pointer.malloc((xs.size + 1) * Fiddle::SIZEOF_VOIDP)\n    a[0, (xs.size + 1) * Fiddle::SIZEOF_VOIDP] = (strs.map(&:to_i) + [0]).pack(\"J*\")\n    [a, strs]\n  end\n\n";
    o += "  # each function, marshaled by kind: String for char*, Array<String> for char**\n";
    for f in &h.funcs {
        let names: Vec<String> = f.params.iter().map(|p| p.name.clone()).collect();
        o += &format!("  def self.{}({})\n", cfg.snake(&f.name), names.join(", "));
        let mut args = Vec::new();
        for p in &f.params {
            if p.ty.is("char", 2) && !p.ty.konst {
                o += &format!("    {n}_a, _keep = strarray({n})\n", n = p.name);
                args.push(format!("{}_a", p.name));
            } else if h.callbacks.iter().any(|c| c.name == p.ty.base)
                || (p.ty.ptr > 0 && !p.ty.is("char", 1))
            {
                args.push(format!("({n} || Fiddle::NULL)", n = p.name));
            } else {
                args.push(p.name.clone());
            }
        }
        let call = format!("{}({})", f.name, args.join(", "));
        let body = if f.ret.is("char", 1) {
            format!("str({call})")
        } else if f.ret.is("char", 2) {
            format!("strs({call})")
        } else if f.ret.is("bool", 0) {
            format!("{call} != 0")
        } else {
            call
        };
        o += &format!("    {body}\n  end\n\n");
    }
    o += "end\n";
    o
}
