//! Python (ctypes): the structures, the callback types, the functions'
//! signatures, and a wrapper per function marshaling by kind (`str` in,
//! `str` and `list[str]` out).

use super::Config;
use super::header::{Header, Ty};

fn ty(h: &Header, t: &Ty) -> String {
    if h.callbacks.iter().any(|c| c.name == t.base) {
        // a CFUNCTYPE is a pointer already
        return t.base.clone();
    }
    let base = match t.base.as_str() {
        "int" => "c_int",
        "short" => "c_short",
        "double" => "c_double",
        "bool" => "c_bool",
        "char" if t.ptr >= 1 => return wrap("c_char_p", t.ptr - 1),
        "void" if t.ptr >= 1 => return wrap("c_void_p", t.ptr - 1),
        "void" => "None",
        s => s,
    };
    wrap(base, t.ptr)
}

fn wrap(base: &str, ptr: u8) -> String {
    let mut s = base.to_string();
    for _ in 0..ptr {
        s = format!("POINTER({s})");
    }
    s
}

fn doc(d: &str, indent: &str) -> String {
    if d.is_empty() {
        return String::new();
    }
    format!(
        "{indent}\"\"\"{}\"\"\"\n",
        d.replace('\\', "\\\\")
            .replace("\"\"\"", "'''")
            .replace('\n', &format!("\n{indent}"))
    )
}

pub fn emit(h: &Header, cfg: &Config) -> String {
    let mut o = String::new();
    o += &cfg.fill("# libngspice for Python (ctypes), generated by ngspice-bindgen from\n");
    o += &cfg.fill("# sharedspice.h. Do not edit: run `cargo run -p ngspice-bindgen`.\n");
    o += &cfg.fill("\"\"\"The libngspice C API (sharedspice.h) for Python.\n\n");
    o += &cfg.fill(
        "    lib = load()                 # libngspice beside, $NGSPICE_LIBRARY, or the system's\n",
    );
    o += "    lib.ngSpice_Init(SendChar(cb), None, None, None, None, None, None)\n";
    o += "    command(lib, \"source deck.cir\")\n\"\"\"\n\n";
    o += "import ctypes\nimport ctypes.util\nimport os\nimport sys\n";
    o += "from ctypes import CFUNCTYPE, POINTER, Structure, c_bool, c_char_p, c_double, c_int, c_short, c_void_p\n\n";
    for s in &h.structs {
        o += &format!("\nclass {}(Structure):\n", s.name);
        o += &doc(&s.doc, "    ");
        o += "    _fields_ = [\n";
        for f in &s.fields {
            o += &format!("        (\"{}\", {}),", f.name, ty(h, &f.ty));
            if !f.doc.is_empty() {
                o += &format!("  # {}", f.doc.replace('\n', " "));
            }
            o += "\n";
        }
        o += "    ]\n\n";
    }
    o += "\n# the callback types: wrap a Python function in one and keep it alive\n";
    for c in &h.callbacks {
        if !c.doc.is_empty() {
            for l in c.doc.lines() {
                o += &format!("# {l}\n");
            }
        }
        let ps: Vec<String> = c.params.iter().map(|p| ty(h, p)).collect();
        o += &format!(
            "{} = CFUNCTYPE({}, {})\n\n",
            c.name,
            ty(h, &c.ret),
            ps.join(", ")
        );
    }
    o += "\ndef load(path=None):\n";
    o += &cfg.fill(
        "    \"\"\"libngspice, its functions typed: `path`, else $NGSPICE_LIBRARY, else the\n",
    );
    o += "    one beside this file, else the system's.\"\"\"\n";
    o += &cfg.fill("    name = {\"darwin\": \"libngspice.dylib\", \"win32\": \"ngspice.dll\"}.get(sys.platform, \"libngspice.so\")\n");
    o += "    here = os.path.join(os.path.dirname(os.path.abspath(__file__)), name)\n";
    o += &cfg.fill("    path = path or os.environ.get(\"NGSPICE_LIBRARY\") or (here if os.path.exists(here) else ctypes.util.find_library(\"ngspice\"))\n");
    o += "    lib = ctypes.CDLL(path)\n";
    for f in &h.funcs {
        let ps: Vec<String> = f.params.iter().map(|p| ty(h, &p.ty)).collect();
        o += &format!("    lib.{}.argtypes = [{}]\n", f.name, ps.join(", "));
        o += &format!("    lib.{}.restype = {}\n", f.name, ty(h, &f.ret));
    }
    o += "    return lib\n\n";
    o += "\ndef _str(p):\n    return None if p is None else p.decode(\"latin-1\")\n\n";
    o += "\ndef _strs(p):\n    out = []\n    i = 0\n    while p and p[i]:\n        out.append(p[i].decode(\"latin-1\"))\n        i += 1\n    return out\n\n";
    o += "\ndef _arg(x):\n    return x.encode(\"latin-1\") if isinstance(x, str) else x\n\n";
    o += "\ndef _strarray(xs):\n    a = (c_char_p * (len(xs) + 1))(*[_arg(x) for x in xs], None)\n    return a\n\n";
    o += "\n# each function, marshaled by kind: str for char*, a list of str for char**\n";
    for f in &h.funcs {
        let snake = cfg.snake(&f.name);
        let names: Vec<String> = f.params.iter().map(|p| p.name.clone()).collect();
        o += &format!(
            "\ndef {snake}(lib{}{}):\n",
            if names.is_empty() { "" } else { ", " },
            names.join(", ")
        );
        o += &doc(&f.doc, "    ");
        let args: Vec<String> = f
            .params
            .iter()
            .map(|p| {
                if h.callbacks.iter().any(|c| c.name == p.ty.base) {
                    // None: a NULL function pointer of the type
                    format!("{} if {} is not None else {}()", p.name, p.name, p.ty.base)
                } else if p.ty.is("char", 1) {
                    format!("_arg({})", p.name)
                } else if p.ty.is("char", 2) && !p.ty.konst {
                    // (a const char** is where a string comes back)
                    format!("_strarray({})", p.name)
                } else {
                    p.name.clone()
                }
            })
            .collect();
        let call = format!("lib.{}({})", f.name, args.join(", "));
        let body = if f.ret.is("char", 1) {
            format!("_str({call})")
        } else if f.ret.is("char", 2) {
            format!("_strs({call})")
        } else {
            call
        };
        o += &format!("    return {body}\n\n");
    }
    o
}
