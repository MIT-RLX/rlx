//! C# (P/Invoke): the structures (sequential), the callback types as
//! delegates, the functions under their C names in `Native`, and a wrapper
//! per function in `Shared` marshaling by kind (`string` in, `string` and
//! `string[]` out).

use super::Config;
use super::header::{Header, Ty};

/// `get_vec_info` → `GetVecInfo`
fn pascal(cfg: &Config, name: &str) -> String {
    cfg.snake(name)
        .split('_')
        .map(|w| {
            let mut c = w.chars();
            c.next()
                .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

/// A field's or a native parameter's type
fn ty(h: &Header, t: &Ty) -> String {
    if h.callbacks.iter().any(|c| c.name == t.base) {
        return t.base.clone();
    }
    if t.ptr > 0 {
        return "IntPtr".into();
    }
    match t.base.as_str() {
        "int" => "int",
        "short" => "short",
        "double" => "double",
        "bool" => "bool",
        "void" => "void",
        s => s,
    }
    .into()
}

/// A bool takes one byte in C
fn marshal(t: &Ty) -> &'static str {
    if t.is("bool", 0) {
        "[MarshalAs(UnmanagedType.I1)] "
    } else {
        ""
    }
}

fn ident(n: &str) -> String {
    match n {
        "type" | "string" | "object" | "params" | "ref" | "out" | "base" | "event" => {
            format!("@{n}")
        }
        _ => n.to_string(),
    }
}

fn doc(d: &str, indent: &str) -> String {
    if d.is_empty() {
        return String::new();
    }
    let mut o = format!("{indent}/// <summary>\n");
    for l in d.lines() {
        o += &format!(
            "{indent}/// {}\n",
            l.replace('&', "&amp;")
                .replace('<', "&lt;")
                .replace('>', "&gt;")
        );
    }
    o + &format!("{indent}/// </summary>\n")
}

pub fn emit(h: &Header, cfg: &Config) -> String {
    let mut o = String::new();
    o += &cfg.fill("// libngspice for C#, generated by ngspice-bindgen from sharedspice.h.\n");
    o += &cfg.fill("// Do not edit: run `cargo run -p ngspice-bindgen`.\n\n");
    o += &cfg.fill("using System;\nusing System.Collections.Generic;\nusing System.Runtime.InteropServices;\n\nnamespace NgSpice\n{\n");
    for s in &h.structs {
        o += &doc(&s.doc, "    ");
        o += &format!(
            "    [StructLayout(LayoutKind.Sequential)]\n    public struct {}\n    {{\n",
            s.name
        );
        for f in &s.fields {
            if !f.doc.is_empty() {
                o += &format!(
                    "        /// <summary>{}</summary>\n",
                    f.doc
                        .replace('\n', " ")
                        .replace('&', "&amp;")
                        .replace('<', "&lt;")
                        .replace('>', "&gt;")
                );
            }
            o += &format!(
                "        {}public {} {};\n",
                marshal(&f.ty),
                ty(h, &f.ty),
                ident(&f.name)
            );
        }
        o += "    }\n\n";
    }
    for c in &h.callbacks {
        o += &doc(&c.doc, "    ");
        let ps: Vec<String> = c
            .params
            .iter()
            .enumerate()
            .map(|(i, p)| format!("{}{} arg{i}", marshal(p), ty(h, p)))
            .collect();
        o += &format!(
            "    [UnmanagedFunctionPointer(CallingConvention.Cdecl)]\n    public delegate {} {}({});\n\n",
            ty(h, &c.ret),
            c.name,
            ps.join(", ")
        );
    }
    o += &cfg.fill("    /// <summary>The functions under their C names. The library: $NGSPICE_LIBRARY, else ngspice's.</summary>\n");
    o += &cfg
        .fill("    public static class Native\n    {\n        const string Lib = \"ngspice\";\n\n");
    o += "        static Native()\n        {\n            NativeLibrary.SetDllImportResolver(typeof(Native).Assembly, (name, asm, path) =>\n            {\n";
    o += &cfg
        .fill("                var p = Environment.GetEnvironmentVariable(\"NGSPICE_LIBRARY\");\n");
    o += "                return name == Lib && p != null ? NativeLibrary.Load(p) : IntPtr.Zero;\n            });\n        }\n\n";
    for f in &h.funcs {
        o += &doc(&f.doc, "        ");
        let ps: Vec<String> = f
            .params
            .iter()
            .map(|p| {
                let t = if p.ty.is("char", 1) {
                    "[MarshalAs(UnmanagedType.LPUTF8Str)] string".to_string()
                } else if p.ty.is("char", 2) && !p.ty.konst {
                    "[MarshalAs(UnmanagedType.LPArray, ArraySubType = UnmanagedType.LPStr)] string?[]".to_string()
                } else {
                    format!("{}{}", marshal(&p.ty), ty(h, &p.ty))
                };
                format!("{t} {}", ident(&p.name))
            })
            .collect();
        if f.ret.is("bool", 0) {
            o += "        [return: MarshalAs(UnmanagedType.I1)]\n";
        }
        o += &format!(
            "        [DllImport(Lib, CallingConvention = CallingConvention.Cdecl)]\n        public static extern {} {}({});\n\n",
            ty(h, &f.ret),
            f.name,
            ps.join(", ")
        );
    }
    o += "    }\n\n";
    o += "    /// <summary>Each function, marshaled by kind: string for char*, string[] for char**.</summary>\n";
    o += "    public static class Shared\n    {\n";
    o += "        static string? Str(IntPtr p) => p == IntPtr.Zero ? null : Marshal.PtrToStringUTF8(p);\n\n";
    o += "        static string[] Strs(IntPtr p)\n        {\n            var o = new List<string>();\n            if (p == IntPtr.Zero) return o.ToArray();\n";
    o += "            for (int i = 0; ; i++)\n            {\n                var q = Marshal.ReadIntPtr(p, i * IntPtr.Size);\n                if (q == IntPtr.Zero) break;\n                o.Add(Marshal.PtrToStringUTF8(q)!);\n            }\n            return o.ToArray();\n        }\n\n";
    for f in &h.funcs {
        let ps: Vec<String> = f
            .params
            .iter()
            .map(|p| {
                let t = if p.ty.is("char", 1) {
                    "string".to_string()
                } else if p.ty.is("char", 2) && !p.ty.konst {
                    "string[]".to_string()
                } else {
                    ty(h, &p.ty)
                };
                format!("{t} {}", ident(&p.name))
            })
            .collect();
        let args: Vec<String> = f
            .params
            .iter()
            .map(|p| {
                if p.ty.is("char", 2) && !p.ty.konst {
                    // NULL-terminated
                    format!("[.. {}, null]", ident(&p.name))
                } else {
                    ident(&p.name)
                }
            })
            .collect();
        let call = format!("Native.{}({})", f.name, args.join(", "));
        let (ret, body) = if f.ret.is("char", 1) {
            ("string?".to_string(), format!("Str({call})"))
        } else if f.ret.is("char", 2) {
            ("string[]".to_string(), format!("Strs({call})"))
        } else {
            (ty(h, &f.ret), call)
        };
        o += &doc(&f.doc, "        ");
        o += &format!(
            "        public static {ret} {}({}) => {body};\n\n",
            pascal(cfg, &f.name),
            ps.join(", ")
        );
    }
    o += "    }\n}\n";
    o
}
