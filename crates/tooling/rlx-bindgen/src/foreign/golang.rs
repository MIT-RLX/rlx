//! Go (cgo): the C declarations in the preamble (from the IR: the header
//! itself is not needed), Go structures laid out as the C ones, each
//! callback type as a Go function type behind an exported trampoline, and
//! a wrapper per function marshaling by kind (`string` in, `string` and
//! `[]string` out).

use super::Config;
use super::header::{Header, Ty};

/// `get_vec_info` → `GetVecInfo`
fn pascal(s: &str) -> String {
    s.split('_')
        .map(|w| {
            let mut c = w.chars();
            c.next()
                .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

/// The C spelling
fn cty(t: &Ty) -> String {
    let base = if t.base == "bool" {
        "bool".to_string()
    } else {
        t.base.clone()
    };
    format!(
        "{}{}{}",
        if t.konst { "const " } else { "" },
        base,
        "*".repeat(t.ptr as usize)
    )
}

/// A Go field's type, laid out as the C one
fn gofield(h: &Header, t: &Ty) -> String {
    if h.callbacks.iter().any(|c| c.name == t.base) || (t.base == "void" && t.ptr > 0) {
        return "unsafe.Pointer".into();
    }
    let base = match t.base.as_str() {
        "int" => "int32".to_string(),
        "short" => "int16".into(),
        "double" => "float64".into(),
        "bool" => "bool".into(),
        "char" => "byte".into(),
        s => pascal(s),
    };
    format!("{}{base}", "*".repeat(t.ptr as usize))
}

/// A wrapper's parameter or result type
fn goarg(h: &Header, t: &Ty) -> String {
    if h.callbacks.iter().any(|c| c.name == t.base) {
        return format!("{}Func", t.base);
    }
    if t.is("char", 1) {
        return "string".into();
    }
    if t.is("char", 2) && !t.konst {
        return "[]string".into();
    }
    match (t.base.as_str(), t.ptr) {
        ("int", 0) => "int".into(),
        ("void", 0) => String::new(),
        _ => gofield(h, t),
    }
}

/// A C value of kind `t` as the wrapper's Go value (in a callback)
fn from_c(h: &Header, t: &Ty, v: &str) -> String {
    let g = goarg(h, t);
    match g.as_str() {
        "string" => format!("C.GoString({v})"),
        "int" => format!("int({v})"),
        "unsafe.Pointer" => v.to_string(),
        g if g.starts_with('*') => format!("({g})(unsafe.Pointer({v}))"),
        g => format!("{g}({v})"),
    }
}

/// A Go value of kind `t` as the C one (into a C call)
fn to_c(t: &Ty, v: &str) -> String {
    if t.base == "void" && t.ptr > 0 {
        return v.to_string();
    }
    if t.ptr > 0 {
        return format!(
            "({}C.{})(unsafe.Pointer({v}))",
            "*".repeat(t.ptr as usize),
            t.base
        );
    }
    match t.base.as_str() {
        "int" => format!("C.int({v})"),
        "short" => format!("C.short({v})"),
        "double" => format!("C.double({v})"),
        "bool" => format!("C.bool({v})"),
        _ => v.to_string(),
    }
}

fn comment(d: &str) -> String {
    d.lines().map(|l| format!("// {l}\n")).collect()
}

pub fn emit(h: &Header, cfg: &Config) -> String {
    let mut o = String::new();
    o +=
        &cfg.fill("// libngspice for Go (cgo), generated by ngspice-bindgen from sharedspice.h.\n");
    o += &cfg.fill("// Do not edit: run `cargo run -p ngspice-bindgen`.\n\n");
    o += &cfg.fill("// Package ngspice is the libngspice C API (sharedspice.h) for Go. Link\n");
    o += &cfg.fill("// with CGO_LDFLAGS=-L<dir of libngspice>; run with the library on the\n");
    o += &cfg.fill("// loader's path.\npackage ngspice\n\n/*\n#cgo LDFLAGS: -lngspice\n#include <stdbool.h>\n#include <stdlib.h>\n\n");
    for s in &h.structs {
        o += &format!("typedef struct {} {{\n", s.name);
        for f in &s.fields {
            o += &format!("    {} {};\n", cty(&f.ty), f.name);
        }
        o += &format!("}} {};\n\n", s.name);
    }
    for c in &h.callbacks {
        let ps: Vec<String> = c.params.iter().map(cty).collect();
        o += &format!("typedef {} ({})({});\n", cty(&c.ret), c.name, ps.join(", "));
        let named: Vec<String> = c.params.iter().map(cty).collect();
        o += &format!(
            "extern {} go{}({});\n",
            cty(&c.ret),
            c.name,
            named.join(", ")
        );
    }
    o += "\n";
    for f in &h.funcs {
        let ps: Vec<String> = f
            .params
            .iter()
            .map(|p| format!("{} {}", cty(&p.ty), p.name))
            .collect();
        o += &format!(
            "extern {} {}({});\n",
            cty(&f.ret),
            f.name,
            if ps.is_empty() {
                "void".into()
            } else {
                ps.join(", ")
            }
        );
    }
    o += "*/\nimport \"C\"\n\nimport \"unsafe\"\n\n";
    for s in &h.structs {
        o += &comment(&s.doc);
        o += &format!("type {} struct {{\n", pascal(&s.name));
        for f in &s.fields {
            o += &format!("\t{} {}", pascal(&f.name), gofield(h, &f.ty));
            if !f.doc.is_empty() {
                o += &format!(" // {}", f.doc.replace('\n', " "));
            }
            o += "\n";
        }
        o += "}\n\n";
    }
    o += &cfg.fill("// the callback types: one Go function of each kind at a time (as\n// ngspice keeps one), called through an exported trampoline\n");
    for c in &h.callbacks {
        o += &comment(&c.doc);
        let ps: Vec<String> = c
            .params
            .iter()
            .enumerate()
            .map(|(i, p)| format!("a{i} {}", goarg(h, p)))
            .collect();
        o += &format!(
            "type {}Func func({}) {}\n\n",
            c.name,
            ps.join(", "),
            goarg(h, &c.ret)
        );
        o += &format!("var cb{} {}Func\n\n", c.name, c.name);
        let cps: Vec<String> = c
            .params
            .iter()
            .enumerate()
            .map(|(i, p)| format!("a{i} {}", cgo(p)))
            .collect();
        o += &format!(
            "//export go{}\nfunc go{}({}) {} {{\n",
            c.name,
            c.name,
            cps.join(", "),
            cgo(&c.ret)
        );
        let args: Vec<String> = c
            .params
            .iter()
            .enumerate()
            .map(|(i, p)| from_c(h, p, &format!("a{i}")))
            .collect();
        o += &format!(
            "\tif cb{} == nil {{\n\t\treturn 0\n\t}}\n\treturn {}(cb{}({}))\n}}\n\n",
            c.name,
            cgo(&c.ret),
            c.name,
            args.join(", ")
        );
    }
    o += "func goStrings(p **C.char) []string {\n\tvar out []string\n\tif p == nil {\n\t\treturn out\n\t}\n";
    o += "\tfor s := unsafe.Slice(p, 1<<20); s[len(out)] != nil; {\n\t\tout = append(out, C.GoString(s[len(out)]))\n\t}\n\treturn out\n}\n\n";
    o += "// each function, marshaled by kind: string for char*, []string for char**\n";
    for f in &h.funcs {
        let name = pascal(&cfg.snake(&f.name));
        let ps: Vec<String> = f
            .params
            .iter()
            .map(|p| format!("{} {}", gname(&p.name), goarg(h, &p.ty)))
            .collect();
        o += &comment(&f.doc);
        o += &format!("func {name}({}) {} {{\n", ps.join(", "), goarg(h, &f.ret));
        let mut args = Vec::new();
        for p in &f.params {
            let n = gname(&p.name);
            if h.callbacks.iter().any(|c| c.name == p.ty.base) {
                o += &format!(
                    "\tcb{} = {n}\n\tvar c{n} *C.{}\n\tif {n} != nil {{\n\t\tc{n} = (*C.{})(C.go{})\n\t}}\n",
                    p.ty.base, p.ty.base, p.ty.base, p.ty.base
                );
                args.push(format!("c{n}"));
            } else if p.ty.is("char", 1) {
                o += &format!("\tc{n} := C.CString({n})\n\tdefer C.free(unsafe.Pointer(c{n}))\n");
                args.push(if p.ty.konst {
                    format!("c{n}")
                } else {
                    format!("c{n}")
                });
            } else if p.ty.is("char", 2) && !p.ty.konst {
                o += &format!(
                    "\tc{n} := (*[1 << 20]*C.char)(C.malloc(C.size_t(len({n})+1) * C.size_t(unsafe.Sizeof(uintptr(0)))))\n"
                );
                o += &format!(
                    "\tdefer C.free(unsafe.Pointer(c{n}))\n\tfor i, s := range {n} {{\n\t\tc{n}[i] = C.CString(s)\n\t\tdefer C.free(unsafe.Pointer(c{n}[i]))\n\t}}\n\tc{n}[len({n})] = nil\n"
                );
                args.push(format!("&c{n}[0]"));
            } else {
                args.push(to_c(&p.ty, &n));
            }
        }
        let call = format!("C.{}({})", f.name, args.join(", "));
        let body = if f.ret.is("char", 1) {
            format!("return C.GoString({call})")
        } else if f.ret.is("char", 2) {
            format!("return goStrings({call})")
        } else if f.ret.base == "void" && f.ret.ptr == 0 {
            call
        } else if f.ret.ptr > 0 {
            format!("return ({})(unsafe.Pointer({call}))", goarg(h, &f.ret))
        } else {
            format!("return {}({call})", goarg(h, &f.ret))
        };
        o += &format!("\t{body}\n}}\n\n");
    }
    o
}

/// A parameter's Go name
fn gname(n: &str) -> String {
    match n {
        "type" | "func" | "range" | "map" | "string" | "var" => format!("{n}_"),
        _ => n.to_string(),
    }
}

/// The cgo spelling of a C type (a trampoline's)
fn cgo(t: &Ty) -> String {
    let base = match t.base.as_str() {
        "void" if t.ptr > 0 => return format!("{}unsafe.Pointer", "*".repeat(t.ptr as usize - 1)),
        "int" => "C.int".to_string(),
        "short" => "C.short".into(),
        "double" => "C.double".into(),
        "bool" => "C.bool".into(),
        "char" => "C.char".into(),
        s => format!("C.{s}"),
    };
    format!("{}{base}", "*".repeat(t.ptr as usize))
}
