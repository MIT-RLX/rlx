//! Swift: the C API through a module map over the generated header
//! (`CNgSpice`), and `NgSpice`, a wrapper per function marshaling by kind
//! (`String` in, `String?` and `[String]` out), the callbacks as
//! `@convention(c)` functions.

use super::Config;
use super::header::{Header, Ty};

/// `get_vec_info` → `getVecInfo`
fn camel(s: &str) -> String {
    let mut o = String::new();
    let mut up = false;
    for ch in s.chars() {
        if ch == '_' {
            up = true;
        } else if up {
            o.push(ch.to_ascii_uppercase());
            up = false;
        } else {
            o.push(ch);
        }
    }
    o
}

/// How Swift imports a C type
fn ty(h: &Header, cfg: &Config, t: &Ty) -> String {
    if h.callbacks.iter().any(|c| c.name == t.base) {
        return format!("{}.{}Fn?", cfg.name, t.base);
    }
    let base = match t.base.as_str() {
        "int" => "Int32".to_string(),
        "short" => "Int16".into(),
        "double" => "Double".into(),
        "bool" => "Bool".into(),
        "char" => "CChar".into(),
        "void" if t.ptr == 0 => return "Void".into(),
        "void" => {
            return format!(
                "{}UnsafeMutableRawPointer?{}",
                "UnsafeMutablePointer<".repeat(t.ptr as usize - 1),
                "?>".repeat(t.ptr as usize - 1)
            );
        }
        s => s.to_string(),
    };
    if t.ptr == 0 {
        return base;
    }
    let mut s = base;
    for k in 0..t.ptr {
        let inner_const = k == 0 && t.konst;
        s = format!(
            "{}<{s}>?",
            if inner_const {
                "UnsafePointer"
            } else {
                "UnsafeMutablePointer"
            }
        );
    }
    s
}

fn comment(d: &str) -> String {
    d.lines().map(|l| format!("    /// {l}\n")).collect()
}

/// The module map: the header, linked with libngspice
pub fn modulemap(cfg: &Config) -> String {
    cfg.fill("// generated by ngspice-bindgen\nmodule CNgSpice {\n    header \"../c/ngspice_shared.h\"\n    link \"ngspice\"\n    export *\n}\n")
}

pub fn emit(h: &Header, cfg: &Config) -> String {
    let mut o = String::new();
    o += &cfg.fill("// libngspice for Swift, generated by ngspice-bindgen from sharedspice.h.\n");
    o += &cfg.fill("// Do not edit: run `cargo run -p ngspice-bindgen`. Import CNgSpice (the\n");
    o += "// module map beside this file) for the C API itself.\n\n";
    o += &cfg.fill(
        "import CNgSpice\n#if canImport(Darwin)\nimport Darwin\n#else\nimport Glibc\n#endif\n\n",
    );
    o += &cfg.fill("/// Each function, marshaled by kind: String for char*, [String] for char**\npublic enum NgSpice {\n");
    o += "    // the callback types, as C function pointers (a func, or a closure\n    // that captures nothing)\n";
    for c in &h.callbacks {
        let ps: Vec<String> = c.params.iter().map(|p| ty(h, cfg, p)).collect();
        o += &comment(&c.doc);
        o += &format!(
            "    public typealias {}Fn = @convention(c) ({}) -> {}\n\n",
            c.name,
            ps.join(", "),
            ty(h, cfg, &c.ret)
        );
    }
    o += "    static func string(_ p: UnsafeMutablePointer<CChar>?) -> String? {\n        p.map { String(cString: $0) }\n    }\n\n";
    o += "    static func strings(_ p: UnsafeMutablePointer<UnsafeMutablePointer<CChar>?>?) -> [String] {\n        var out: [String] = []\n        guard let p = p else { return out }\n        var i = 0\n        while let s = p[i] {\n            out.append(String(cString: s))\n            i += 1\n        }\n        return out\n    }\n\n";
    for f in &h.funcs {
        let mut ps = Vec::new();
        let mut pre = String::new();
        let mut post = String::new();
        let mut args = Vec::new();
        let mut wrap_open = String::new();
        let mut wrap_close = String::new();
        for p in &f.params {
            let n = p.name.clone();
            if p.ty.is("char", 1) {
                ps.push(format!("_ {n}: String"));
                // char*: a copy the call may keep
                pre += &format!("        let {n}c = strdup({n})\n");
                post += &format!("        free({n}c)\n");
                args.push(format!("{n}c"));
            } else if p.ty.is("char", 2) && !p.ty.konst {
                ps.push(format!("_ {n}: [String]"));
                pre += &format!(
                    "        var {n}c: [UnsafeMutablePointer<CChar>?] = {n}.map {{ strdup($0) }} + [nil]\n"
                );
                post += &format!("        {n}c.forEach {{ free($0) }}\n");
                wrap_open += &format!("{n}c.withUnsafeMutableBufferPointer {{ {n}b in ");
                wrap_close += " }";
                args.push(format!("{n}b.baseAddress"));
            } else {
                ps.push(format!("_ {n}: {}", ty(h, cfg, &p.ty)));
                args.push(n);
            }
        }
        let call = format!("{wrap_open}{}({}){wrap_close}", f.name, args.join(", "));
        let (ret, expr) = if f.ret.is("char", 1) {
            ("String?".to_string(), format!("string({call})"))
        } else if f.ret.is("char", 2) {
            ("[String]".to_string(), format!("strings({call})"))
        } else {
            (ty(h, cfg, &f.ret), call)
        };
        o += &comment(&f.doc);
        let name = camel(&cfg.snake(&f.name));
        // (`NgSpice.init(...)` would read as a constructor)
        let name = match name.as_str() {
            "init" => "initialize".to_string(),
            "deinit" | "subscript" | "func" | "var" | "let" | "return" | "self" | "Type" => {
                format!("`{name}`")
            }
            _ => name,
        };
        o += &format!(
            "    @discardableResult\n    public static func {name}({}) -> {ret} {{\n{pre}",
            ps.join(", ")
        );
        if post.is_empty() {
            o += &format!("        return {expr}\n    }}\n\n");
        } else {
            o += &format!("        let r = {expr}\n{post}        return r\n    }}\n\n");
        }
    }
    o += "}\n";
    o
}
