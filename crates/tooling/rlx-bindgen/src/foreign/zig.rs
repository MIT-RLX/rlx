//! Zig: the C API through `@cImport` of the generated header (`c`), and a
//! wrapper per function marshaling by kind (`[:0]const u8` in, `?[:0]const
//! u8` out, a `char**` list from a slice of strings with an allocator).

use super::Config;
use super::header::Header;

/// `get_vec_info` → `getVecInfo`
fn camel(s: &str) -> String {
    let mut o = String::new();
    let mut up = false;
    for ch in s.chars() {
        if ch == '_' {
            up = true;
        } else if up {
            o.push(ch.to_ascii_uppercase());
            up = false;
        } else {
            o.push(ch);
        }
    }
    o
}

fn comment(d: &str) -> String {
    d.lines().map(|l| format!("/// {l}\n")).collect()
}

pub fn emit(h: &Header, cfg: &Config) -> String {
    let mut o = String::new();
    o += &cfg.fill("//! libngspice for Zig, generated by ngspice-bindgen from sharedspice.h.\n");
    o += &cfg.fill("//! Do not edit: run `cargo run -p ngspice-bindgen`. Build with the\n");
    o += &cfg.fill("//! directory of ngspice_shared.h on the include path and -lngspice.\n\n");
    o += &cfg.fill("const std = @import(\"std\");\n\n/// The C API as declared (structures, callback types, functions)\npub const c = @cImport({\n    @cInclude(\"ngspice_shared.h\");\n});\n\n");
    o += "// each function, marshaled by kind: [:0]const u8 for char*, a slice of\n// strings for an incoming char**\n";
    for f in &h.funcs {
        let mut ps = Vec::new();
        let mut args = Vec::new();
        let mut pre = String::new();
        let mut fallible = false;
        for p in &f.params {
            let n = format!("{}_", p.name);
            if p.ty.is("char", 1) {
                ps.push(format!("{n}: [:0]const u8"));
                args.push(format!("@constCast({n}.ptr)"));
            } else if p.ty.is("char", 2) && !p.ty.konst {
                fallible = true;
                ps.push(format!(
                    "alloc: std.mem.Allocator, {n}: []const [:0]const u8"
                ));
                pre += &format!(
                    "    const {n}c = try alloc.alloc([*c]u8, {n}.len + 1);\n    defer alloc.free({n}c);\n"
                );
                pre += &format!(
                    "    for ({n}, 0..) |s, i| {n}c[i] = @constCast(s.ptr);\n    {n}c[{n}.len] = null;\n"
                );
                args.push(format!("{n}c.ptr"));
            } else {
                ps.push(format!(
                    "{n}: @typeInfo(@TypeOf(c.{})).@\"fn\".params[{}].type.?",
                    f.name,
                    args.len()
                ));
                args.push(n);
            }
        }
        let call = format!("c.{}({})", f.name, args.join(", "));
        let (ret, body) = if f.ret.is("char", 1) {
            (
                "?[:0]const u8".to_string(),
                format!("const p = {call};\n    return if (p == null) null else std.mem.span(p);"),
            )
        } else {
            (
                format!("@typeInfo(@TypeOf(c.{})).@\"fn\".return_type.?", f.name),
                format!("return {call};"),
            )
        };
        let ret = if fallible { format!("!{ret}") } else { ret };
        o += &comment(&f.doc);
        o += &format!(
            "pub fn {}({}) {ret} {{\n{pre}    {body}\n}}\n\n",
            camel(&cfg.snake(&f.name)),
            ps.join(", ")
        );
    }
    o
}
