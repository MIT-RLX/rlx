//! A plain C header of the list (no export macro, no `#ifdef`s, the
//! callback types as function pointers): what Swift and Zig import.

use super::Config;
use super::header::{Header, Ty};

fn cty(t: &Ty) -> String {
    format!(
        "{}{}{}",
        if t.konst { "const " } else { "" },
        t.base,
        "*".repeat(t.ptr as usize)
    )
}

fn comment(d: &str, indent: &str) -> String {
    if d.is_empty() {
        return String::new();
    }
    let mut o = format!("{indent}/*\n");
    for l in d.lines() {
        o += &format!("{indent} * {}\n", l.replace("*/", "* /"));
    }
    o + &format!("{indent} */\n")
}

pub fn emit(h: &Header, cfg: &Config) -> String {
    let mut o = String::new();
    o += &cfg.fill("/* libngspice's C API, generated by ngspice-bindgen from sharedspice.h\n");
    o += &cfg.fill(" * (the export macro and the #ifdefs resolved). Do not edit: run\n * `cargo run -p ngspice-bindgen`. */\n\n");
    o += &cfg.fill("#ifndef NGSPICE_SHARED_H\n#define NGSPICE_SHARED_H\n\n#include <stdbool.h>\n\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n");
    for s in &h.structs {
        o += &comment(&s.doc, "");
        o += &format!("typedef struct {} {{\n", s.name);
        for f in &s.fields {
            o += &format!("    {} {};", cty(&f.ty), f.name);
            if !f.doc.is_empty() {
                o += &format!(" /* {} */", f.doc.replace('\n', " ").replace("*/", "* /"));
            }
            o += "\n";
        }
        o += &format!("}} {};\n\n", s.name);
    }
    for c in &h.callbacks {
        o += &comment(&c.doc, "");
        let ps: Vec<String> = c.params.iter().map(cty).collect();
        o += &format!(
            "typedef {} ({})({});\n\n",
            cty(&c.ret),
            c.name,
            ps.join(", ")
        );
    }
    for f in &h.funcs {
        o += &comment(&f.doc, "");
        let ps: Vec<String> = f
            .params
            .iter()
            .map(|p| format!("{} {}", cty(&p.ty), p.name))
            .collect();
        o += &format!(
            "{} {}({});\n\n",
            cty(&f.ret),
            f.name,
            if ps.is_empty() {
                "void".into()
            } else {
                ps.join(", ")
            }
        );
    }
    o += "#ifdef __cplusplus\n}\n#endif\n\n#endif\n";
    o
}
