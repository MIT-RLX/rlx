//! Julia (`ccall`): the structures, the functions under their C names, and
//! a wrapper per function marshaling by kind (`String` in, `String` and
//! `Vector{String}` out), the callbacks as `@cfunction` pointers.

use super::Config;
use super::header::{Header, Ty};

fn ty(h: &Header, t: &Ty, field: bool) -> String {
    if h.callbacks.iter().any(|c| c.name == t.base) {
        return "Ptr{Cvoid}".into();
    }
    let base = match t.base.as_str() {
        "int" => "Cint".to_string(),
        "short" => "Cshort".into(),
        "double" => "Cdouble".into(),
        "bool" => "Bool".into(),
        "char" if t.ptr == 1 && !field => return "Cstring".into(),
        "char" => "UInt8".into(),
        "void" if t.ptr == 0 => return "Cvoid".into(),
        "void" => "Cvoid".into(),
        s => s.to_string(),
    };
    let mut s = base;
    for _ in 0..t.ptr {
        s = format!("Ptr{{{s}}}");
    }
    s
}

fn doc(d: &str) -> String {
    if d.is_empty() {
        return String::new();
    }
    format!(
        "\"\"\"\n{}\n\"\"\"\n",
        d.replace('\\', "\\\\")
            .replace('$', "\\$")
            .replace("\"\"\"", "'''")
    )
}

pub fn emit(h: &Header, cfg: &Config) -> String {
    let mut o = String::new();
    o += &cfg.fill("# libngspice for Julia, generated by ngspice-bindgen from sharedspice.h.\n");
    o += &cfg.fill("# Do not edit: run `cargo run -p ngspice-bindgen`.\n\n");
    o += &cfg.fill("\"\"\"\nThe libngspice C API (sharedspice.h) for Julia.\n\n");
    o += &cfg.fill(
        "    NgSpiceShared.load()          # \\$NGSPICE_LIBRARY, else the system's libngspice\n",
    );
    o += "    cb = @cfunction(f, Cint, (Cstring, Cint, Ptr{Cvoid}))\n";
    o += &cfg.fill(
        "    NgSpiceShared.init(cb, C_NULL, C_NULL, C_NULL, C_NULL, C_NULL, C_NULL)\n\"\"\"\n",
    );
    o += &cfg
        .fill("module NgSpiceShared\n\nusing Libdl\n\nconst handle = Ref{Ptr{Cvoid}}(C_NULL)\n\n");
    o += &cfg.fill("\"\"\"libngspice: `path`, else \\$NGSPICE_LIBRARY, else the system's\"\"\"\n");
    o += &cfg.fill("function load(path = get(ENV, \"NGSPICE_LIBRARY\", \"libngspice\"))\n    handle[] = Libdl.dlopen(path)\nend\n\n");
    o += "sym(name) = Libdl.dlsym(handle[], name)\n\n";
    for s in &h.structs {
        o += &doc(&s.doc);
        o += &format!("struct {}\n", s.name);
        for f in &s.fields {
            o += &format!("    {}::{}", f.name, ty(h, &f.ty, true));
            if !f.doc.is_empty() {
                o += &format!("  # {}", f.doc.replace('\n', " "));
            }
            o += "\n";
        }
        o += "end\n\n";
    }
    o += "# the callback types (pass `@cfunction(f, ret, (args...))`)\n";
    for c in &h.callbacks {
        let ps: Vec<String> = c.params.iter().map(|p| ty(h, p, false)).collect();
        o += &format!(
            "# {}: {} ({})\n",
            c.name,
            ty(h, &c.ret, false),
            ps.join(", ")
        );
    }
    o += "\n# the functions under their C names\n";
    for f in &h.funcs {
        let names: Vec<String> = f.params.iter().map(|p| p.name.clone()).collect();
        let tys: Vec<String> = f.params.iter().map(|p| ty(h, &p.ty, false)).collect();
        let tup = if tys.len() == 1 {
            format!("({},)", tys[0])
        } else {
            format!("({})", tys.join(", "))
        };
        o += &doc(&f.doc);
        o += &format!(
            "{}({}) = ccall(sym(:{}), {}, {}{}{})\n\n",
            f.name,
            names.join(", "),
            f.name,
            // (a char* result as a pointer: ccall returns no Cstring)
            ty(h, &f.ret, true),
            tup,
            if names.is_empty() { "" } else { ", " },
            names.join(", ")
        );
    }
    o += "_str(p) = p == C_NULL ? nothing : unsafe_string(p)\n\n";
    o += "function _strs(p)\n    out = String[]\n    p == C_NULL && return out\n    i = 1\n    while (q = unsafe_load(p, i)) != C_NULL\n        push!(out, unsafe_string(q))\n        i += 1\n    end\n    out\nend\n\n";
    o += "# each function, marshaled by kind: String for char*, Vector{String} for char**\n";
    for f in &h.funcs {
        let names: Vec<String> = f.params.iter().map(|p| p.name.clone()).collect();
        o += &format!("function {}({})\n", cfg.snake(&f.name), names.join(", "));
        let mut pre = String::new();
        let args: Vec<String> = f
            .params
            .iter()
            .map(|p| {
                if p.ty.is("char", 2) && !p.ty.konst {
                    pre += &format!(
                        "    {n}_p = [map(pointer, {n}); Ptr{{UInt8}}(C_NULL)]\n",
                        n = p.name
                    );
                    format!("{}_p", p.name)
                } else {
                    p.name.clone()
                }
            })
            .collect();
        o += &pre;
        let call = format!("{}({})", f.name, args.join(", "));
        let preserve: Vec<String> = f
            .params
            .iter()
            .filter(|p| p.ty.is("char", 2) && !p.ty.konst)
            .map(|p| p.name.clone())
            .collect();
        let call = if preserve.is_empty() {
            call
        } else {
            format!("GC.@preserve {} {call}", preserve.join(" "))
        };
        let body = if f.ret.is("char", 1) {
            format!("_str(Ptr{{UInt8}}({call}))")
        } else if f.ret.is("char", 2) {
            format!("_strs({call})")
        } else {
            call
        };
        o += &format!("    {body}\nend\n\n");
    }
    o += "end # module\n";
    o
}
