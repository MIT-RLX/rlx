fn func_name(name: &str) -> String {
    let c = camel(name);
    if RESERVED.contains(&c.to_ascii_lowercase().as_str()) {
        format!("{c}_")
    } else {
        c
    }
}

/// Method names may be keywords in PHP 8, except a few the engine claims.
fn method_name(name: &str) -> String {
    let c = camel(name);
    match c.as_str() {
        "close" | "adopt" => format!("{c}_"),
        _ if c.starts_with("__") => format!("{c}_"),
        _ => c,
    }
}

fn var(name: &str) -> String {
    match camel(name).as_str() {
        "this" | "k" => format!("${}_", camel(name)),
        c => format!("${c}"),
    }
}

fn ty(kind: &str) -> String {
    match kind {
        "str" => "string",
        "str?" => "?string",
        "json" | "value" | "json?" | "value?" => "mixed",
        "bool" => "bool",
        "f32" | "f64" => "float",
        "i32" | "u32" | "node" | "i64" | "u64" | "usize" => "int",
        "node?" | "u64?" | "usize?" => "?int",
        "f32?" => "?float",
        "usizes?" | "strs?" => "?array",
        "u8s" => "string",
        "f32s" | "u32s" | "nodes" | "usizes" | "i64s" | "rows2" | "frows2" | "frows6" | "strs"
        | "inputs" | "typed_inputs" => "array",
        "graph" | "graph&" => "Graph",
        "graph?" => "?Graph",
        other => return other.trim_end_matches('&').to_string(),
    }
    .to_string()
}

fn ret_ty(kind: &str) -> String {
    match kind {
        "str" => "string",
        "str?" => "?string",
        "json" => "mixed",
        "object" | "rows" | "shapes" | "shape" | "strings" | "f32s" | "u32s" | "nodes"
        | "outputs" | "typed_outputs" | "tensors" => "array",
        "u8s" => "string",
        "bool" => "bool",
        "usize" | "u64" | "u32" | "node" => "int",
        "f32" => "float",
        "f32?" => "?float",
        "graph" => "Graph",
        other => other,
    }
    .to_string()
}

fn literal(l: &Lit) -> String {
    match l {
        Lit::None => "null".into(),
        Lit::Bool(b) => b.to_string(),
        Lit::Num(n) => n.replace("inf", "INF"),
        Lit::Str(s) => format!("'{s}'"),
        Lit::List(items) => {
            let inner: Vec<String> = items.iter().map(literal).collect();
            format!("[{}]", inner.join(", "))
        }
    }
}

/// PHP expressions for one parameter's C arguments (`$k` keeps buffers alive).
fn lower(p: &Param, v: &str) -> Vec<String> {
    match p.kind.as_str() {
        "json" | "value" | "json?" | "value?" => vec![format!("S::json({v})")],
        "node?" => vec![format!("{v} ?? NONE")],
        "u64?" | "usize?" => vec![format!("S::box($k, 'uint64_t', {v})")],
        "f32?" => vec![format!("S::box($k, 'float', {v})")],
        "f32s" => vec![format!("S::arr($k, 'float', {v})"), format!("count({v})")],
        "u8s" => vec![format!("S::bytes($k, {v})"), format!("strlen({v})")],
        "u32s" | "nodes" => vec![
            format!("S::arr($k, 'uint32_t', {v})"),
            format!("count({v})"),
        ],
        "usizes" => vec![format!("S::arr($k, 'size_t', {v})"), format!("count({v})")],
        "i64s" => vec![format!("S::arr($k, 'int64_t', {v})"), format!("count({v})")],
        "usizes?" => vec![
            format!("{v} === null ? null : S::arr($k, 'size_t', {v})"),
            format!("{v} === null ? 0 : count({v})"),
        ],
        "rows2" => vec![
            format!("S::arr($k, 'size_t', S::rows({v}, 2, true))"),
            format!("count({v})"),
        ],
        "frows2" => vec![
            format!("S::arr($k, 'float', S::rows({v}, 2, false))"),
            format!("count({v})"),
        ],
        "frows6" => vec![
            format!("S::arr($k, 'float', S::rows({v}, 6, false))"),
            format!("count({v})"),
        ],
        "strs" | "strs?" => vec![
            format!("S::strs($k, {v})"),
            format!("{v} === null ? 0 : count({v})"),
        ],
        "inputs" => {
            let n = format!("$in_{}", p.name);
            vec![
                format!("{n}[0]"),
                format!("{n}[1]"),
                format!("{n}[2]"),
                format!("{n}[3]"),
            ]
        }
        "typed_inputs" => {
            let n = format!("$in_{}", p.name);
            vec![
                format!("{n}[0]"),
                format!("{n}[1]"),
                format!("{n}[2]"),
                format!("{n}[3]"),
                format!("{n}[4]"),
            ]
        }
        "graph?" => vec![format!("{v}?->h")],
        "str" | "str?" | "bool" | "f32" | "f64" | "i32" | "u32" | "node" | "i64" | "u64"
        | "usize" => vec![v.to_string()],
        _ => vec![format!("{v}->h")],
    }
}

/// `(declarations, C arguments, PHP result)` for one result, given its C
/// out-parameter types.
fn outs(kind: &str, i: usize, c: &[String]) -> (Vec<String>, Vec<String>, String) {
    let o = format!("$o{i}");
    let base = c[0].trim_end_matches('*').to_string();
    let base = if c[0].ends_with("**") {
        format!("{base}*")
    } else {
        base
    };
    let mut d = vec![format!("{o} = S::ffi()->new('{base}');")];
    let mut a = vec![format!("FFI::addr({o})")];
    if kind == "f32?" {
        d.push(format!("{o}k = S::ffi()->new('bool');"));
        a.push(format!("FFI::addr({o}k)"));
    }
    let e = match kind {
        "str" => format!("S::takeString({o})"),
        "str?" => format!("S::takeStringOrNull({o})"),
        "json" | "object" | "rows" | "shapes" | "shape" | "strings" => {
            format!("S::decode(S::takeString({o}))")
        }
        "f32s" => format!("S::takeF32s({o})"),
        "u8s" => format!("S::takeBytes({o})"),
        "u32s" | "nodes" => format!("S::takeU32s({o})"),
        "outputs" => format!("S::takeOutputs({o})"),
        "typed_outputs" => format!("S::takeTypedOutputs({o})"),
        "tensors" => format!("S::takeTensors({o})"),
        "bool" | "u32" | "node" | "usize" | "u64" => format!("{o}->cdata"),
        "f32" => format!("(float) {o}->cdata"),
        "f32?" => format!("{o}k->cdata ? (float) {o}->cdata : null"),
        "graph" => format!("Graph::adopt({o})"),
        class => format!("{class}::adopt({o})"),
    };
    (d, a, e)
}

/// A gated function's declaration with every pointer as `void*`, for its own
/// `FFI::cdef` on first use.
fn gated_decl(ir: &Ir, f: &Func) -> String {
    let params: Vec<String> = c_params(ir, f)
        .iter()
        .enumerate()
        .map(|(i, (t, _))| {
            if t == "const char*" {
                format!("const char* a{i}")
            } else if t.contains('*') {
                format!("void* a{i}")
            } else {
                format!("{t} a{i}")
            }
        })
        .collect();
    format!("int32_t {}({});", f.c, params.join(", "))
}

fn func(s: &mut String, ir: &Ir, f: &Func, defaults: &[String], indent: &str) {
    let class = ir.class_of(f).map(|c| c.name.clone());
    let mut sig: Vec<String> = Vec::new();
    for p in &f.params {
        let t = ty(&p.kind);
        if p.optional() {
            let (t, d) = match &p.default {
                Some(Lit::None) | None => {
                    let t = if t.starts_with('?') || t == "mixed" {
                        t
                    } else {
                        format!("?{t}")
                    };
                    (t, "null".to_string())
                }
                // bytes are a PHP string
                Some(Lit::List(items)) if p.kind == "u8s" && items.is_empty() => (t, "''".into()),
                Some(d) => (t, literal(d)),
            };
            sig.push(format!("{t} {} = {d}", var(&p.name)));
        } else {
            sig.push(format!("{t} {}", var(&p.name)));
        }
    }
    let rets: Vec<(String, String)> = match f.role {
        Role::Constructor => vec![],
        _ => f.rets.clone(),
    };
    let ret = match rets.as_slice() {
        [] => "void".to_string(),
        [(_, k)] => ret_ty(k),
        _ => "array".to_string(),
    };
    let doc = doc_lines(&f.doc, &format!("{indent} * "));
    if !doc.trim().is_empty() {
        let _ = write!(s, "{indent}/**\n{}{indent} */\n", doc.replace("*/", "* /"));
    }
    let head = match f.role {
        Role::Constructor => format!("public function __construct({})", sig.join(", ")),
        Role::Static => format!(
            "public static function {}({}): {ret}",
            method_name(&f.name),
            sig.join(", ")
        ),
        Role::Method => format!(
            "public function {}({}): {ret}",
            method_name(&f.name),
            sig.join(", ")
        ),
        Role::Function => format!("function {}({}): {ret}", func_name(&f.name), sig.join(", ")),
    };
    let _ = writeln!(s, "{indent}{head}\n{indent}{{");
    let start = s.len();
    let b = format!("{indent}    ");
    let _ = writeln!(s, "{b}$k = [];");
    let mut args = Vec::new();
    if f.role == Role::Method {
        args.push("$this->h".to_string());
    }
    for p in &f.params {
        let v = var(&p.name);
        match p.kind.as_str() {
            "inputs" => {
                let _ = writeln!(s, "{b}$in_{} = S::inputs($k, {v});", p.name);
            }
            "typed_inputs" => {
                let _ = writeln!(s, "{b}$in_{} = S::typedInputs($k, {v});", p.name);
            }
            _ => {}
        }
        args.extend(lower(p, &v));
    }
    let gated = f.feature.as_ref().is_some_and(|x| !defaults.contains(x));
    let lib = if gated {
        format!("S::gated('{}')", gated_decl(ir, f))
    } else {
        "S::ffi()".to_string()
    };
    if f.direct {
        match f.rets.first().map(|(_, k)| k.as_str()) {
            Some("str") => {
                // PHP's FFI returns a `const char*` as a string.
                let _ = writeln!(s, "{b}return {lib}->{}({});", f.c, args.join(", "));
            }
            _ => {
                let _ = writeln!(s, "{b}return (bool) {lib}->{}({});", f.c, args.join(", "));
            }
        }
        drop_unused_keep(s, start);
        let _ = writeln!(s, "{indent}}}\n");
        return;
    }
    let all_rets: Vec<(String, String)> = match f.role {
        Role::Constructor => vec![("handle".into(), class.clone().unwrap())],
        _ => f.rets.clone(),
    };
    let mut exprs = Vec::new();
    for (i, (_, k)) in all_rets.iter().enumerate() {
        let c = crate::ir::c_outs(k);
        let (d, a, e) = outs(k, i, &c);
        for line in d {
            let _ = writeln!(s, "{b}{line}");
        }
        args.extend(a);
        exprs.push(e);
    }
    let _ = writeln!(s, "{b}S::check({lib}->{}({}));", f.c, args.join(", "));
    match (f.role, exprs.len()) {
        (Role::Constructor, _) => {
            let _ = writeln!(s, "{b}$this->h = $o0;");
        }
        (_, 0) => {}
        (_, 1) => {
            let _ = writeln!(s, "{b}return {};", exprs[0]);
        }
        _ => {
            let fields: Vec<String> = rets
                .iter()
                .zip(&exprs)
                .map(|((n, _), e)| format!("'{}' => {e}", camel(n)))
                .collect();
            let _ = writeln!(s, "{b}return [{}];", fields.join(", "));
        }
    }
    drop_unused_keep(s, start);
    let _ = writeln!(s, "{indent}}}\n");
}

/// Remove a body's `$k = [];` (from `start`) when nothing else names `$k`.
fn drop_unused_keep(s: &mut String, start: usize) {
    let body = &s[start..];
    let first = body.find('\n').map_or(body.len(), |i| i + 1);
    if !body[first..].contains("$k") {
        s.replace_range(start..start + first, "");
    }
}

/// `src/Generated.php`.
pub fn generate(ir: &Ir, defaults: &[String]) -> String {
    let mut s = String::from(
        "<?php\n\
         // RLX — versatile ML compiler + runtime.\n\
         // Copyright (C) 2026 Eugene Hauptmann, Nataliya Kosmyna.\n\
         // SPDX-License-Identifier: MIT OR Apache-2.0\n\
         \n\
         // @generated by rlx-bindgen from rlx-bind's op table and runtime API table —\n\
         // do not edit; regenerate with `just gen-bindings`.\n\
         \n\
         declare(strict_types=1);\n\
         \n\
         namespace Rlx;\n\
         \n\
         use FFI;\n\
         use Rlx\\Support as S;\n\n",
    );
    for f in ir.free_funcs().filter(|f| !f.manual) {
        func(&mut s, ir, f, defaults, "");
    }
    for c in &ir.classes {
        let doc = doc_lines(&c.doc, " * ");
        let _ = writeln!(s, "/**\n{doc} */");
        let _ = writeln!(s, "final class {} extends Handle\n{{", c.name);
        if ir.members(c).any(|f| f.manual) {
            let _ = writeln!(s, "    use Manual\\{}Rows;\n", c.name);
        }
        let _ = writeln!(s, "    protected const FREE = '{}';\n", c.c_free());
        for f in ir.members(c).filter(|f| !f.manual) {
            func(&mut s, ir, f, defaults, "    ");
        }
        s.truncate(s.trim_end().len());
        s.push_str("\n}\n\n");
    }
    s.truncate(s.trim_end().len());
    s.push('\n');
    s
}
