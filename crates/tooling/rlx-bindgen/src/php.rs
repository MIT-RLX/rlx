//! The PHP binding (PHP 8.1+, the FFI extension), from the lowered [`Ir`]:
//!
//! * `rlx-php/src/rlx_php.h` — rlx-capi's header as PHP's FFI parser takes
//!   it: no preprocessor lines, and no functions behind a feature the default
//!   build lacks (those are declared on first use, so a library without them
//!   still loads).
//! * `rlx-php/src/Generated.php` — namespace `Rlx`: a class per handle type
//!   (freed in `__destruct`, or early with `close()`), free functions as
//!   namespaced functions. Optional parameters are PHP defaults, so named
//!   arguments work (`$g->softmax($x, axis: 1)`). `Optimizer::step` and
//!   `Trainer::run` come from hand-written traits (`Manual.php`).

use std::fmt::Write;

use rlx_bind::api::Role;

use crate::ir::{Func, Ir, Lit, Param, camel, doc_lines};
use crate::jni::c_params;

/// rlx.h for `FFI::cdef`.
pub fn header(rlx_h: &str, ir: &Ir, defaults: &[String]) -> String {
    // `cdef` resolves every function it declares, so it gets none that
    // librlx_capi may lack: non-default features, and the function only a
    // library that links model plugins defines.
    let gated: Vec<&str> = ir
        .funcs
        .iter()
        .filter(|f| f.feature.as_ref().is_some_and(|x| !defaults.contains(x)))
        .map(|f| f.c.as_str())
        .chain(["rlx_link_model_plugins"])
        .collect();
    let mut out = String::from(
        "/* @generated by rlx-bindgen from rlx-capi's header — do not edit;\n\
         \x20* regenerate with `just gen-bindings`. rlx.h for PHP's FFI::cdef: no\n\
         \x20* preprocessor lines, no functions behind a non-default feature. */\n",
    );
    let mut skip = false;
    let mut in_cpp = false;
    for line in rlx_h.lines() {
        let t = line.trim_start();
        if t.starts_with("#ifdef __cplusplus") {
            in_cpp = true;
            continue;
        }
        if in_cpp {
            in_cpp = !t.starts_with("#endif");
            continue;
        }
        if t.starts_with('#') {
            continue;
        }
        if !skip
            && gated.iter().any(|g| {
                t.split_once('(')
                    .and_then(|(head, _)| head.split_whitespace().last())
                    .is_some_and(|n| n.trim_start_matches('*') == *g)
            })
        {
            skip = true;
        }
        if skip {
            skip = !t.contains(");");
            continue;
        }
        out.push_str(line);
        out.push('\n');
    }
    out
}

