//! The `class Graph` section of `pyrlx/_pyrlx.pyi`, between the
//! `# <rlx-bindgen: Graph>` / `# </rlx-bindgen: Graph>` markers.

use std::fmt::Write;

use rlx_bind::{ArgSpec, OpSpec};

use crate::kinds::literal;

const OPEN: &str = "# <rlx-bindgen: Graph>\n";
const CLOSE: &str = "# </rlx-bindgen: Graph>\n";

fn ty(kind: &str) -> String {
    let s = match kind {
        "node" => "NodeId",
        "opt_node" => "NodeId | None",
        "nodes" => "Sequence[NodeId]",
        "f32" | "f64" => "float",
        "i32" | "i64" | "u32" | "u64" | "usize" => "int",
        "bool" => "bool",
        "usizes" | "i64s" => "Sequence[int]",
        "pair" | "triple" => "int | Sequence[int]",
        "opt_pair" => "int | Sequence[int] | None",
        "opt_usizes" => "Sequence[int] | None",
        "f32s" | "f32x3" => "Sequence[float]",
        "bytes" => "bytes",
        "opt_usize" => "int | None",
        "opt_f32" => "float | None",
        "pads" => "Sequence[int | Sequence[int]]",
        "bands" | "sos" => "Sequence[Sequence[float]]",
        "graph" => "Graph",
        "opt_graph" => "Graph | None",
        "str" | "opt_str" => {
            return if kind == "str" {
                "str".into()
            } else {
                "str | None".into()
            };
        }
        "dtype" => "DTypeName",
        "activation" => "ActivationName",
        "opt_activation" => "ActivationName | None",
        "binop" => "BinaryOpName",
        "cmp_op" => "CompareName",
        "reduce_op" => "ReduceName",
        "fft_norm" => "FftNormName",
        "mask" => "MaskKindName",
        "rope_style" => "RopeStyleName",
        "interp" => "InterpName",
        "scatter_red" => "ScatterReductionName",
        "fir_mode" => "FirModeName",
        "window" => "WindowName",
        "spd_fn" => "SpdFnName",
        "vq_metric" => "VqMetricName",
        "quant_scheme" => "QuantSchemeName",
        other => {
            // Any other enum kind: its spellings as a Literal.
            let names = rlx_bind::enums::ALL_KINDS
                .iter()
                .find(|(k, _)| *k == other)
                .map(|(_, n)| *n)
                .unwrap_or(&[]);
            if names.is_empty() {
                return "str".into();
            }
            let quoted: Vec<String> = names.iter().map(|n| format!("\"{n}\"")).collect();
            return format!("Literal[{}]", quoted.join(", "));
        }
    };
    s.to_string()
}

fn ret(r: &str) -> &'static str {
    match r {
        "node" => "NodeId",
        "pair" => "tuple[NodeId, NodeId]",
        "nodes" => "list[NodeId]",
        "unit" => "None",
        "shape" => "tuple[list[int], str]",
        "strings" => "list[str]",
        "usize" => "int",
        _ => "str",
    }
}

fn param(a: &ArgSpec) -> String {
    match a.default {
        Some(d) => format!(
            "{}: {} = {}",
            a.name,
            ty(a.kind),
            literal(d, "None", "True", "False")
        ),
        None => format!("{}: {}", a.name, ty(a.kind)),
    }
}

fn stub(s: &mut String, name: &str, op: &OpSpec) {
    let params: Vec<String> = op.args.iter().map(param).collect();
    let one_line = format!(
        "    def {name}(self{}) -> {}: ...",
        params.iter().map(|p| format!(", {p}")).collect::<String>(),
        ret(op.ret)
    );
    if one_line.len() <= 100 {
        let _ = writeln!(s, "{one_line}");
        return;
    }
    let _ = writeln!(s, "    def {name}(");
    let _ = writeln!(s, "        self,");
    for p in &params {
        let _ = writeln!(s, "        {p},");
    }
    let _ = writeln!(s, "    ) -> {}: ...", ret(op.ret));
}

/// The generated `class Graph` block.
pub fn generate(ops: &[OpSpec]) -> String {
    let mut s = String::from(OPEN);
    s.push_str(
        "# @generated by rlx-bindgen from rlx-bind's op table — do not edit;\n\
         # regenerate with `just gen-bindings`.\n\
         class Graph:\n\
         \x20   \"\"\"Symbolic RLX graph. Consumed by ``Session.compile``.\n\
         \n\
         \x20   Methods return integer node ids. Shape-inferred builders (``matmul``,\n\
         \x20   ``gelu``, ``conv2d``, …) omit ``out_shape``; explicit-shape variants\n\
         \x20   (``matmul_with_shape``, ``lora_matmul``) take one. Trailing option\n\
         \x20   parameters (``conv2d(x, w, kernel_size=3, stride=2)``) may be passed\n\
         \x20   positionally or by keyword.\n\
         \x20   \"\"\"\n\
         \n\
         \x20   def __init__(self, name: str) -> None: ...\n\
         \x20   def __len__(self) -> int: ...\n\
         \x20   def __repr__(self) -> str: ...\n",
    );
    for op in ops {
        stub(&mut s, op.name, op);
        for alias in op.py_aliases() {
            stub(&mut s, alias, op);
        }
    }
    s.push_str(CLOSE);
    s
}

/// `text` with its marked section replaced by [`generate`].
pub fn splice(text: &str, ops: &[OpSpec]) -> String {
    let (Some(start), Some(end)) = (text.find(OPEN), text.find(CLOSE)) else {
        panic!(
            "rlx-bindgen: _pyrlx.pyi has no `{}` … `{}` markers",
            OPEN.trim(),
            CLOSE.trim()
        );
    };
    format!(
        "{}{}{}",
        &text[..start],
        generate(ops),
        &text[end + CLOSE.len()..]
    )
}
