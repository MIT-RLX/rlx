/// The workspace root, from this crate's location.
pub fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../..")
        .canonicalize()
        .expect("workspace root")
}

/// Every generated file: `(path relative to the workspace root, contents)`.
pub fn outputs(root: &Path) -> Vec<(PathBuf, String)> {
    let ops = rlx_bind::manifest();
    let capi_dir = Path::new("crates/bindings/rlx-capi");
    let graph_ops = capi::generate(ops);

    let sources = capi_sources(root, &graph_ops);
    let rlx_h = header::generate(&sources);

    // The runtime table must match the C ABI exactly before Swift is printed
    // from it.
    let table = rlx_bind::api::api();
    let fns = header::functions(&sources);
    let errors = api::check(table, &fns);
    assert!(
        errors.is_empty(),
        "rlx-bindgen: api.idl and rlx-capi disagree:\n  {}",
        errors.join("\n  ")
    );
    let lowered = ir::build(ops, table, &fns).unwrap_or_else(|e| {
        panic!(
            "rlx-bindgen: the tables and rlx-capi disagree:\n  {}",
            e.join("\n  ")
        )
    });
    let defaults = capi_default_features(&root.join(capi_dir).join("Cargo.toml"));
    let mut api_md = docs::generate(ops);
    let footer = "\n## License\n";
    let at = api_md.rfind(footer).expect("docs footer");
    api_md.insert_str(at, &api::docs(table));

    let pyi_path = PathBuf::from("crates/bindings/pyrlx/python/pyrlx/_pyrlx.pyi");
    let pyi_text = std::fs::read_to_string(root.join(&pyi_path)).expect("reading _pyrlx.pyi");

    let go_files = golang::generate(&lowered, &defaults);
    let php_h = php::header(&rlx_h, &lowered, &defaults);
    let (node_js, node_ts) = node::generate(&lowered);
    let mut out = vec![
        (capi_dir.join("src/graph_ops.rs"), graph_ops),
        (capi_dir.join("include/rlx.h"), rlx_h.clone()),
        // The R, V and OCaml packages carry the header, so they install on
        // their own.
        (
            PathBuf::from("crates/bindings/rlx-r/src/rlx.h"),
            rlx_h.clone(),
        ),
        (
            PathBuf::from("crates/bindings/rlx-ocaml/src/rlx.h"),
            rlx_h.clone(),
        ),
        (
            PathBuf::from("crates/bindings/rlx-elixir/c_src/rlx.h"),
            rlx_h.clone(),
        ),
        (PathBuf::from("crates/bindings/rlx-v/rlx.h"), rlx_h),
        (
            PathBuf::from("crates/bindings/rlx-swift/Sources/RLX/GraphOps.swift"),
            swift::generate(ops),
        ),
        (
            PathBuf::from("crates/bindings/rlx-swift/Sources/RLX/API.swift"),
            api::swift(table, &fns, &defaults),
        ),
        (
            PathBuf::from("crates/bindings/rlx-cpp/include/rlx/rlx.hpp"),
            cpp::generate(&lowered),
        ),
        (
            PathBuf::from("crates/bindings/rlx-csharp/src/Rlx/RLX.g.cs"),
            csharp::generate(&lowered),
        ),
        (
            PathBuf::from("crates/bindings/rlx-java/src/main/java/org/rlx/RLX.java"),
            java::generate(&lowered),
        ),
        (
            PathBuf::from("crates/bindings/rlx-julia/src/generated.jl"),
            julia::generate(&lowered),
        ),
        (
            PathBuf::from("crates/bindings/rlx-ruby/lib/rlx/generated.rb"),
            ruby::generate(&lowered),
        ),
        (
            PathBuf::from("crates/bindings/rlx-zig/src/rlx.zig"),
            zig::generate(&lowered),
        ),
        (
            PathBuf::from("crates/bindings/rlx-kotlin/src/main/c/rlx_jni.c"),
            jni::generate(&lowered, &defaults),
        ),
        (
            PathBuf::from("crates/bindings/rlx-kotlin/src/main/kotlin/org/rlx/kt/RLX.kt"),
            kotlin::generate(&lowered),
        ),
        (
            PathBuf::from("crates/bindings/rlx-lua/src/rlx_core.c"),
            lua::c_module(&lowered, &defaults),
        ),
        (
            PathBuf::from("crates/bindings/rlx-lua/rlx/generated.lua"),
            lua::lua_api(&lowered),
        ),
        (
            PathBuf::from("crates/bindings/rlx-node/lib/rlx.js"),
            node_js,
        ),
        (
            PathBuf::from("crates/bindings/rlx-node/lib/rlx.d.ts"),
            node_ts,
        ),
        (pyi_path, pyi::splice(&pyi_text, ops)),
        (PathBuf::from("docs/bindings-api.md"), api_md),
    ];
    out.push((
        PathBuf::from("crates/bindings/rlx-odin/rlx/generated.odin"),
        odin::generate(&lowered, &defaults),
    ));
    out.push((
        PathBuf::from("crates/bindings/rlx-elixir/c_src/rlx_nif.c"),
        elixir::nif_source(&lowered, &defaults),
    ));
    out.push((
        PathBuf::from("crates/bindings/rlx-elixir/lib/rlx/generated.ex"),
        elixir::api(&lowered),
    ));
    out.push((
        PathBuf::from("crates/bindings/rlx-ocaml/src/rlx_stubs.c"),
        ocaml::stubs(&lowered, &defaults),
    ));
    out.push((
        PathBuf::from("crates/bindings/rlx-ocaml/src/generated.ml"),
        ocaml::api(&lowered),
    ));
    out.push((
        PathBuf::from("crates/bindings/rlx-haskell/src/RLX/Generated.hs"),
        haskell::generate(&lowered, &defaults),
    ));
    out.push((
        PathBuf::from("crates/bindings/rlx-v/generated.v"),
        vlang::generate(&lowered, &defaults),
    ));
    let d_dir = PathBuf::from("crates/bindings/rlx-d/source/rlx");
    out.push((d_dir.join("capi.d"), dlang::capi(&lowered, &defaults)));
    out.push((
        d_dir.join("generated.d"),
        dlang::generate(&lowered, &defaults),
    ));
    out.push((
        PathBuf::from("crates/bindings/rlx-nim/src/rlx/generated.nim"),
        nim::generate(&lowered),
    ));
    out.push((
        PathBuf::from("crates/bindings/rlx-php/src/rlx_php.h"),
        php_h,
    ));
    out.push((
        PathBuf::from("crates/bindings/rlx-php/src/Generated.php"),
        php::generate(&lowered, &defaults),
    ));
    let r_dir = PathBuf::from("crates/bindings/rlx-r");
    out.push((r_dir.join("src/rlx_r.c"), r::c_glue(&lowered, &defaults)));
    out.push((r_dir.join("R/generated.R"), r::r_api(&lowered)));
    out.push((r_dir.join("NAMESPACE"), r::namespace(&lowered)));
    out.push((
        PathBuf::from("crates/bindings/rlx-dart/lib/src/generated.dart"),
        dart::generate(&lowered),
    ));
    out.push((
        PathBuf::from("crates/bindings/rlx-matlab/src/rlx_mex.c"),
        matlab::mex(&lowered, &defaults),
    ));
    for (file, text) in matlab::api(&lowered) {
        out.push((PathBuf::from("crates/bindings/rlx-matlab").join(file), text));
    }
    for (file, text) in go_files {
        out.push((PathBuf::from("crates/bindings/rlx-go").join(file), text));
    }
    out
}

/// rlx-capi's `default` feature list, read from its manifest.
fn capi_default_features(manifest: &Path) -> Vec<String> {
    let text = std::fs::read_to_string(manifest).expect("reading rlx-capi/Cargo.toml");
    let line = text
        .lines()
        .find(|l| l.trim_start().starts_with("default"))
        .expect("rlx-capi has a default feature list");
    line.split('"')
        .skip(1)
        .step_by(2)
        .map(str::to_string)
        .collect()
}

/// rlx-capi's sources, in module order, with the generated graph builders
/// taken from memory so the header and checks never lag them.
pub fn capi_sources(root: &Path, graph_ops: &str) -> Vec<header::Source> {
    let capi_dir = Path::new("crates/bindings/rlx-capi");
    let order = [
        "ffi.rs",
        "graph.rs",
        "graph_ops.rs",
        "compose.rs",
        "runtime.rs",
        "io.rs",
        "train.rs",
        "text.rs",
        "dist.rs",
        "model.rs",
    ];
    order
        .iter()
        .map(|f| header::Source {
            file: (*f).to_string(),
            text: if *f == "graph_ops.rs" {
                graph_ops.to_string()
            } else {
                std::fs::read_to_string(root.join(capi_dir).join("src").join(f))
                    .unwrap_or_else(|e| panic!("rlx-bindgen: reading rlx-capi/src/{f}: {e}"))
            },
        })
        .collect()
}

/// Every function rlx-capi exports.
pub fn capi_functions(root: &Path) -> Vec<header::CFn> {
    let graph_ops = capi::generate(rlx_bind::manifest());
    header::functions(&capi_sources(root, &graph_ops))
}

/// Files whose on-disk contents differ from what would be generated.
pub fn stale(root: &Path) -> Vec<PathBuf> {
    outputs(root)
        .into_iter()
        .filter(|(path, text)| {
            std::fs::read_to_string(root.join(path)).ok().as_deref() != Some(text)
        })
        .map(|(path, _)| path)
        .collect()
}
