//! Synthesis scripts + optional board constraints for FPGA export.
//!
//! RTL (`top.sv`) is always target-agnostic. These sidecars tell Yosys /
//! nextpnr how to map soft ports onto a concrete part when requested.

#[allow(unused_imports)]
use crate::prelude::*;

use crate::codegen::Artifact;
use crate::export_config::{FpgaExportConfig, HwTarget};
use crate::model::Model;
use crate::xc7::{UART_BAUD, UART_SYNC, Xc7Board};

/// Emit `synth.sh`, `EXPORT.md`, and optional constraint files.
pub fn collect_synth_artifacts(model: &Model, cfg: &FpgaExportConfig) -> Vec<Artifact> {
    let mut out = Vec::new();
    if cfg.emit_synth_scripts {
        out.push(Artifact {
            rel_path: "synth.sh".into(),
            content: emit_synth_sh(&cfg.hw_target, cfg.emit_board_shell),
        });
        out.push(Artifact {
            rel_path: "EXPORT.md".into(),
            content: emit_export_md(model, cfg),
        });
    }
    if cfg.emit_synth_scripts
        && cfg.emit_board_shell
        && let Some(board) = cfg.hw_target.xc7()
    {
        out.push(Artifact {
            rel_path: "program.sh".into(),
            content: emit_xc7_program_sh(board),
        });
        out.push(Artifact {
            rel_path: "run_uart.py".into(),
            content: emit_run_uart_py(model, cfg),
        });
    }
    if cfg.emit_constraints && cfg.hw_target.emits_constraints() {
        if let Some((path, body)) = emit_constraints(&cfg.hw_target) {
            out.push(Artifact {
                rel_path: path,
                content: body,
            });
        }
    }
    out
}

fn emit_synth_sh(hw: &HwTarget, board_shell: bool) -> String {
    let mut s = String::from(
        "#!/usr/bin/env bash\nset -euo pipefail\n# Generated by rlx-fpga — do not hand-edit.\ncd \"$(dirname \"$0\")\"\n\n",
    );
    match hw {
        HwTarget::Generic => {
            s.push_str(
                r#"# Target-agnostic: Yosys generic synth to a JSON netlist.
# Soft ports only — wrap `top` with a board shell for pin mapping.
yosys -p 'read_verilog -sv top.sv layers/*.sv primitives/*.sv; hierarchy -top top; synth -top top; write_json out.json'
echo "wrote out.json (generic). Bind pins in a board wrapper before P&R."
"#,
            );
        }
        HwTarget::Ecp5 { device, package } => {
            s.push_str(&format!(
                r#"yosys -p 'read_verilog -sv top.sv layers/*.sv primitives/*.sv; synth_ecp5 -top top -json out.json'
nextpnr-ecp5 --json out.json --textcfg out.config --{device} --package {package}
ecppack out.config out.bit
echo "wrote out.bit"
"#
            ));
        }
        HwTarget::Ice40 { device, package } => {
            s.push_str(&format!(
                r#"yosys -p 'read_verilog -sv top.sv layers/*.sv primitives/*.sv; synth_ice40 -top top -json out.json'
nextpnr-ice40 --json out.json --pcf constraints.pcf --{device} --package {package} --asc out.asc
icepack out.asc out.bin
echo "wrote out.bin"
"#
            ));
        }
        HwTarget::Xilinx7 { part, board } => {
            let board = board.filter(|_| board_shell);
            s.push_str(&emit_openxc7_flow(part, board));
        }
    }
    s
}

/// openXC7: yosys → nextpnr-xilinx → fasm2frames → xc7frames2bit.
fn emit_openxc7_flow(part: &str, board: Option<Xc7Board>) -> String {
    let family = board.map(Xc7Board::family).unwrap_or("artix7");
    let (top, sources, freq) = match board {
        Some(b) => (
            "board_top",
            "board_top.sv top.sv layers/*.sv primitives/*.sv",
            b.pins().clk_mhz,
        ),
        None => ("top", "top.sv layers/*.sv primitives/*.sv", 100),
    };
    let pnr_guard = if board.is_none() {
        r#"
if ! grep -q '^set_property' constraints.xdc; then
    echo "synthesized out.json for $PART. No board preset: write board_top + constraints.xdc"
    echo "(or export with HwTarget::xc7_board) before place-and-route."
    exit 0
fi
"#
    } else {
        ""
    };
    format!(
        r#"# openXC7 (https://github.com/openXC7): yosys → nextpnr-xilinx → fasm2frames → xc7frames2bit.
# Install: `snap install openxc7 --classic`, or point the variables below at a source build.
PART="${{PART:-{part}}}"
FAMILY="${{FAMILY:-{family}}}"
TOP="${{TOP:-{top}}}"
FREQ_MHZ="${{FREQ_MHZ:-{freq}}}"
OPENXC7_PREFIX="${{OPENXC7_PREFIX:-/snap/openxc7/current/opt}}"
# First existing of: snap layout, source-tree layout, regymm/openxc7 container.
first_dir() {{ for d in "$@"; do [ -d "$d" ] && {{ echo "$d"; return; }}; done; echo "$1"; }}
PRJXRAY_DB_DIR="${{PRJXRAY_DB_DIR:-$(first_dir \
    "$OPENXC7_PREFIX/nextpnr-xilinx/external/prjxray-db" \
    "$OPENXC7_PREFIX/nextpnr-xilinx/xilinx/external/prjxray-db" \
    /nextpnr-xilinx/xilinx/external/prjxray-db)}}"
NEXTPNR_XILINX_PYTHON_DIR="${{NEXTPNR_XILINX_PYTHON_DIR:-$(first_dir \
    "$OPENXC7_PREFIX/nextpnr-xilinx/xilinx/python" \
    "$OPENXC7_PREFIX/nextpnr-xilinx/python" \
    /nextpnr-xilinx/xilinx/python)}}"
CHIPDB_DIR="${{CHIPDB_DIR:-${{XDG_CACHE_HOME:-$HOME/.cache}}/rlx-fpga/chipdb}}"

for tool in yosys nextpnr-xilinx fasm2frames xc7frames2bit; do
    command -v "$tool" >/dev/null || {{ echo "missing $tool — install openXC7 (https://github.com/openXC7)"; exit 1; }}
done

# -nolutram: nextpnr-xilinx cannot pack distributed RAM (RAM64X1S & co.);
# small buffers go to block RAM / flops instead.
yosys -q -l yosys.log -p "read_verilog -sv {sources}; synth_xilinx -flatten -abc9 -nolutram -family xc7 ${{YOSYS_SYNTH_OPTS:-}} -top $TOP; write_json out.json"
{pnr_guard}
# nextpnr-xilinx chipdb: built once per part (minutes), cached across exports.
if [ ! -f "$CHIPDB_DIR/$PART.bin" ]; then
    command -v bbasm >/dev/null || {{ echo "missing bbasm (ships with nextpnr-xilinx)"; exit 1; }}
    PYPY="${{PYPY:-$(command -v pypy3 || command -v python3)}}"
    mkdir -p "$CHIPDB_DIR"
    echo "building chipdb for $PART → $CHIPDB_DIR (one-time)"
    "$PYPY" "$NEXTPNR_XILINX_PYTHON_DIR/bbaexport.py" --device "$PART" --bba "$CHIPDB_DIR/$PART.bba"
    bbasm -l "$CHIPDB_DIR/$PART.bba" "$CHIPDB_DIR/$PART.bin"
    rm -f "$CHIPDB_DIR/$PART.bba"
fi

nextpnr-xilinx --chipdb "$CHIPDB_DIR/$PART.bin" --xdc constraints.xdc --json out.json \
    --fasm out.fasm --freq "$FREQ_MHZ" -l nextpnr.log ${{NEXTPNR_OPTS:-}}
fasm2frames --part "$PART" --db-root "$PRJXRAY_DB_DIR/$FAMILY" out.fasm > out.frames
xc7frames2bit --part_file "$PRJXRAY_DB_DIR/$FAMILY/$PART/part.yaml" --part_name "$PART" \
    --frm_file out.frames --output_file out.bit
echo "wrote out.bit"
"#
    )
}

fn emit_xc7_program_sh(board: Xc7Board) -> String {
    format!(
        r#"#!/usr/bin/env bash
set -euo pipefail
# Generated by rlx-fpga — do not hand-edit.
cd "$(dirname "$0")"
# Load out.bit into SRAM (lost on power-off). FLASH=1 writes the SPI flash instead.
[ -f out.bit ] || {{ echo "out.bit missing — run ./synth.sh first"; exit 1; }}
if [ "${{FLASH:-0}}" = "1" ]; then
    openFPGALoader -b {loader} --write-flash out.bit
else
    openFPGALoader -b {loader} out.bit
fi
"#,
        loader = board.loader_board()
    )
}

/// Host side of the UART link (pyserial). Sends `.mem` stimulus files
/// (one hex byte per line, the `tb_image.mem` format) and prints the reply.
fn emit_run_uart_py(model: &Model, cfg: &FpgaExportConfig) -> String {
    let out_len = crate::codegen::io_ports::primary_out_len(model).max(1);
    let send_pred = cfg.io.output.wants_pred_port();
    let send_mem = cfg.io.output.wants_memory();
    format!(
        r#"#!/usr/bin/env python3
# Generated by rlx-fpga — do not hand-edit.
"""Run `{name}` on the board over the UART host link.

    python3 run_uart.py [--port PORT] [--expect-pred N] input.mem [input.mem ...]

Each .mem file is the stimulus format of tb.sv: one hex byte (i8) per line.
Needs pyserial (`pip install pyserial`).
"""
import argparse
import sys

INPUT_LEN = {in_len}
OUT_LEN = {out_len}
SEND_PRED = {send_pred}
SEND_MEM = {send_mem}
SYNC = 0x{sync:02X}
BAUD = {baud}


def load_mem(path):
    with open(path) as f:
        vals = [int(t, 16) & 0xFF for t in f.read().split()]
    if len(vals) != INPUT_LEN:
        sys.exit(f"{{path}}: {{len(vals)}} bytes, model wants {{INPUT_LEN}}")
    return bytes(vals)


def find_port():
    from serial.tools import list_ports

    # Digilent boards: FTDI FT2232, UART on the second interface.
    ftdi = sorted(p.device for p in list_ports.comports() if p.vid == 0x0403)
    if not ftdi:
        sys.exit("no FTDI serial port found; pass --port")
    return ftdi[-1]


def signed(b):
    return b - 256 if b > 127 else b


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--port")
    ap.add_argument("--timeout", type=float, default=2.0)
    ap.add_argument("--expect-pred", type=int)
    ap.add_argument("mem", nargs="+")
    a = ap.parse_args()

    import serial

    reply_len = int(SEND_PRED) + (OUT_LEN if SEND_MEM else 0)
    with serial.Serial(a.port or find_port(), BAUD, timeout=a.timeout) as port:
        port.reset_input_buffer()
        ok = True
        for path in a.mem:
            port.write(bytes([SYNC]) + load_mem(path))
            reply = port.read(reply_len)
            if len(reply) != reply_len:
                sys.exit(f"{{path}}: got {{len(reply)}}/{{reply_len}} reply bytes (board programmed? right port?)")
            line = [path]
            if SEND_PRED:
                line.append(f"pred={{signed(reply[0])}}")
                if a.expect_pred is not None and signed(reply[0]) != a.expect_pred:
                    ok = False
                    line.append(f"(expected {{a.expect_pred}})")
            if SEND_MEM:
                line.append("logits=" + ",".join(str(signed(b)) for b in reply[int(SEND_PRED):]))
            print(" ".join(line))
        sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
"#,
        name = model.name,
        in_len = model.input_len,
        send_pred = if send_pred { "True" } else { "False" },
        send_mem = if send_mem { "True" } else { "False" },
        sync = UART_SYNC,
        baud = UART_BAUD,
    )
}

fn emit_export_md(model: &Model, cfg: &FpgaExportConfig) -> String {
    format!(
        r#"# RLX FPGA export — `{name}`

| Field | Value |
|-------|-------|
| Model | `{name}` |
| Input length | {input_len} |
| Layers | {n_layers} |
| Tune | `{tune}` |
| Hardware target | {hw} |
| RTL | **target-agnostic** SystemVerilog (`top.sv` soft ports) |

## Ports (`top`)

| Port | Dir | Role |
|------|-----|------|
{ports}

## Soft I/O

| Field | Value |
|-------|-------|
| Input iface | `{in_iface:?}` |
| Output iface | `{out_iface:?}` |
| Bind input | `{bind_in}` |
| Bind outputs | `{bind_out}` |

## Build

```sh
bash synth.sh
```

Generic target produces `out.json` only. Board targets (`ecp5`, `ice40`, …)
run place-and-route when the open toolchain is on `PATH`.

## Parity

Bit-exact reference: `rlx_fpga::reference` (Rust) ↔ emitted Verilog.
Do not diff against f32 Cortex-M requant paths.
"#,
        name = model.name,
        input_len = model.input_len,
        n_layers = model.layers.len(),
        tune = cfg.tune,
        hw = cfg.hw_target,
        ports = crate::codegen::io_ports::port_table_md(&cfg.io, model),
        in_iface = cfg.io.input,
        out_iface = cfg.io.output,
        bind_in = cfg.io.bind.input.as_deref().unwrap_or("(first Op::Input)"),
        bind_out = if cfg.io.bind.outputs.is_empty() {
            "(graph.outputs[0])".into()
        } else {
            cfg.io.bind.outputs.join(", ")
        },
    )
}

fn emit_constraints(hw: &HwTarget) -> Option<(String, String)> {
    match hw {
        HwTarget::Generic => None,
        HwTarget::Ecp5 { .. } => Some((
            "constraints.lpf".into(),
            r#"# Stub Lattice ECP5 constraints — map soft ports to board pins.
# BLOCK RESETPATHS;
# BLOCK ASYNCPATHS;
# LOCATE COMP "clk" SITE "P6";
# IOBUF PORT "clk" IO_TYPE=LVCMOS33;
# LOCATE COMP "rst" SITE "...";
# LOCATE COMP "start" SITE "...";
# LOCATE COMP "done" SITE "...";
"#
            .into(),
        )),
        HwTarget::Ice40 { .. } => Some((
            "constraints.pcf".into(),
            r#"# Stub iCE40 PCF — map soft ports to board pins.
# set_io clk 35
# set_io rst 37
# set_io start 34
# set_io done 32
"#
            .into(),
        )),
        HwTarget::Xilinx7 {
            board: Some(board), ..
        } => Some(("constraints.xdc".into(), emit_xc7_xdc(*board))),
        HwTarget::Xilinx7 { .. } => Some((
            "constraints.xdc".into(),
            r#"# Stub Xilinx XDC — map soft ports to board pins.
# set_property PACKAGE_PIN <PIN> [get_ports clk]
# set_property IOSTANDARD LVCMOS33 [get_ports clk]
"#
            .into(),
        )),
    }
}

/// Pin constraints for an openXC7 board (`board_top` ports).
fn emit_xc7_xdc(board: Xc7Board) -> String {
    let p = board.pins();
    let mut s =
        format!("# {board} — board_top pins (Digilent master XDC). Generated by rlx-fpga.\n");
    let mut pin = |port: &str, loc: &str| {
        s.push_str(&format!(
            "set_property PACKAGE_PIN {loc} [get_ports {{{port}}}]\n\
             set_property IOSTANDARD LVCMOS33 [get_ports {{{port}}}]\n"
        ));
    };
    pin("clk", p.clk);
    pin("rst_btn", p.rst);
    pin("uart_rx", p.uart_rx);
    pin("uart_tx", p.uart_tx);
    for (i, l) in p.leds.iter().enumerate() {
        pin(&format!("led[{i}]"), l);
    }
    s
}
